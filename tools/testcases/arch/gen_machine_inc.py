#!/usr/bin/env python3
"""gen_machine_inc.py — render assembler geometry headers from the profile table.

The Makefile builds tests/shared/bootrom/*.S directly, so those sources cannot
receive llvm-mc --defsym from a driver.  They include a committed header that is
generated from tests/shared/machine-profiles.yaml:

    tests/shared/asm/machine-<profile>.inc

Arch vectors are driven by run_m5_e2e.py and use --defsym instead (same table).

Usage:
  gen_machine_inc.py           # write both headers
  gen_machine_inc.py --check   # byte-compare with disk; rc=1 on drift
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "lib"))
import machine_profile  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.abspath(__file__)))))
OUT_DIR = os.path.join(ROOT, "tests", "shared", "asm")


def render(prof):
    lines = [
        "@@ Generated by tools/testcases/arch/gen_machine_inc.py — DO NOT EDIT",
        "@@ Source: tests/shared/machine-profiles.yaml (profile %s)" % prof.name,
        ".equ RAM_BASE, %#x" % prof.ram_base,
        ".equ RAM_END, %#x" % prof.ram_end,
        ".equ RAM_SIZE, %#x" % prof["ram_size"],
        ".equ ENTRY, %#x" % prof.entry,
        ".equ SP, %#x" % prof.sp,
        ".equ BOOTROM_BASE, %#x" % prof.bootrom_base,
        ".equ BOOTROM_SIZE, %#x" % prof["bootrom_size"],
        ".equ RESET_PC, %#x" % prof.reset_pc,
        ".equ EXIT_BLOCK, %#x" % prof.exit_block,
        ".equ DUMP_BASE, %#x" % prof.dump_base,
    ]
    # hmon 的同步 fault 记录槽（TESTCASES-092t）；无 monitor 的 profile 不定义。
    if prof.fault_record is not None:
        lines.append(".equ FAULT_RECORD, %#x" % prof.fault_record)
    lines += [
        ".equ HMON_BASE, 0x0fff00000000",
        ".equ SMON_BASE, 0x0bff00000000",
        ".equ PMEM_BASE, 0x47ff00000000",
        "",
    ]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    rc = 0
    for name, prof in sorted(machine_profile.all_profiles().items()):
        path = os.path.join(OUT_DIR, "machine-%s.inc" % name)
        text = render(prof)
        if check:
            try:
                with open(path, encoding="utf-8") as fh:
                    have = fh.read()
            except OSError as exc:
                print("gen_machine_inc: MISSING %s (%s)" % (path, exc))
                rc = 1
                continue
            if have != text:
                print("gen_machine_inc: DRIFT %s" % path)
                rc = 1
            else:
                print("gen_machine_inc: OK %s" % path)
        else:
            os.makedirs(OUT_DIR, exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            print("gen_machine_inc: wrote %s" % path)
    return rc


if __name__ == "__main__":
    sys.exit(main())
