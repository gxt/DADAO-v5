def _lds_section_base(text: str, section: str) -> int:
    """链接布局里某段之前的最后一个 `. = <hex> [+ <hex>…];` ⇒ 该段起始地址。"""
    lines = text.splitlines()
    idx = None
    for i, line in enumerate(lines):
        if re.match(r"\s*\.%s\s*:" % re.escape(section), line):
            idx = i
            break
    if idx is None:
        raise ExpectError("链接布局找不到段 .%s" % section)
    for line in reversed(lines[:idx]):
        m = re.match(r"\s*\.\s*=\s*(0x[0-9A-Fa-f]+"
                     r"(?:\s*\+\s*0x[0-9A-Fa-f]+)*)\s*;", line)
        if m:
            return sum(int(v, 16) for v in m.group(1).split("+"))
    raise ExpectError("链接布局段 .%s 之前没有地址赋值" % section)


def _lds_layout(root: Path) -> dict:
    text = (root / DEFAULT_LDS).read_text(encoding="utf-8")
    return {"entry": _lds_section_base(text, "text"),
            "testdata": _lds_section_base(text, "testdata")}


def _book_dirs(root: Path, books: str) -> list:
    base = root / books
    dirs = sorted(p for p in base.iterdir() if p.is_dir() and list(p.glob("*.S")))
    if not dirs:
        raise ExpectError("%s 下没有任何含 .S 的册目录" % books)
    return dirs


def derive_image(root: Path, src: Path) -> Image:
    layout = _lds_layout(root)
    eng = _Engine(root)
    eng.symbols["ENTRY"] = layout["entry"]
    eng.run_file(src)
    eng.finish()
    data = bytes(eng.sections.get(".testdata", b""))
    slots = []
    for i, s in enumerate(eng.slots, 1):
        value = s["value"]
        if isinstance(value, tuple):
            addr = value[1]
            off = addr - layout["testdata"]
            if off < 0 or off + 8 > len(data):
                raise ExpectError("%s 槽 %d：数据区地址 0x%x 越界（.testdata %d B）"
                                  % (src, i, addr, len(data)))
            value = int.from_bytes(data[off:off + 8], "big")
        slots.append(Slot(i, s["kind"], value, s["expr"], s["detail"],
                          s["source"]))
    return Image(str(src.relative_to(root)), slots)


def derive(root: Path, books: str = DEFAULT_BOOKS) -> list:
    root = Path(root)
    images = []
    for d in _book_dirs(root, books):
        for src in sorted(d.glob("*.S")):
            images.append(derive_image(root, src))
    return images


