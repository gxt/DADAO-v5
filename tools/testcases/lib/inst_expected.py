def render_expected(images) -> str:
    out = [_HEADER]
    for img in sorted(images, key=lambda x: x.path):
        for s in img.slots:
            exp = "-" if s.value is None else "0x%016x" % s.value
            detail = " ".join(str(s.expr if s.kind != "relation" else s.detail)
                              .split())
            out.append("\t".join((img.path, str(s.index), s.kind, exp,
                                  detail, s.source)) + "\n")
    return "".join(out)


def input_paths(root: Path) -> list:
    root = Path(root)
    paths = set()
    for pat in _INPUT_GLOBS:
        for p in root.glob(pat):
            if p.is_file():
                paths.add(p.relative_to(root))
    return sorted(str(p) for p in paths)


def render_inputs(root: Path) -> str:
    root = Path(root)
    lines = []
    for rel in input_paths(root):
        digest = hashlib.sha256((root / rel).read_bytes()).hexdigest()
        lines.append("%s  %s\n" % (digest, rel))
    return "".join(lines)


def write_data(root: Path) -> dict:
    root = Path(root)
    images = derive(root)
    outdir = root / DATA_DIR
    outdir.mkdir(parents=True, exist_ok=True)
    files = {
        EXPECTED_NAME: render_expected(images),
        INPUTS_NAME: render_inputs(root),
    }
    for name, text in files.items():
        (outdir / name).write_text(text, encoding="utf-8")
    return {"images": images, "files": files}


def expected_path(root: Path) -> Path:
    return Path(root) / DATA_DIR / EXPECTED_NAME


def inputs_path(root: Path) -> Path:
    return Path(root) / DATA_DIR / INPUTS_NAME
