@dataclass
class Slot:
    index: int
    kind: str
    value: int | None
    expr: str
    detail: str
    source: str


@dataclass
class Image:
    path: str          # 相对仓库根
    slots: list = field(default_factory=list)


class ExpectError(Exception):
    """派生失败（语法超出本展开器 / 符号不可求值 / 文档漂移）—— fail-closed。"""


def _strip_comment(line: str) -> str:
    i = line.find("@@")
    return line if i < 0 else line[:i]


def _split_args(text: str) -> list:
    """按**顶层**逗号切分；`{}`/`[]`/`()` 内的逗号不切（汇编操作数组）。"""
    out, cur, depth = [], [], 0
    for ch in text:
        if ch in "{[(":
            depth += 1
        elif ch in "}])":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if cur or text.strip():
        out.append("".join(cur).strip())
    return out


class _Engine:
    """最小汇编宏展开器：只解释影响「展开顺序 / 条件 / 符号 / 数据区」的指令。"""

    def __init__(self, root: Path):
        self.root = root
        self.macros = {}
        self.symbols = {}
        self.slots = []
        self.section = None
        self.sections = {}
        self.regs = {}          # 抽象寄存器值：set.rd/set.rb/ld.o
        self.pending = None     # 上一槽的期望（等 `__NCHECK` 加一建槽）
        self.cur_macro = None
        self.depth = 0

    # ---- 表达式求值 ----
    def ev(self, expr: str) -> int:
        e = expr.strip()
        while e.startswith("(") and e.endswith(")"):
            depth, ok = 0, True
            for i, ch in enumerate(e):
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                    if depth == 0 and i != len(e) - 1:
                        ok = False
                        break
            if not ok:
                break
            e = e[1:-1].strip()

        def repl(m):
            name = m.group(0)
            if name in self.symbols:
                return str(self.symbols[name])
            if name in ("rd0", "rb0", "ra0", "rf0"):
                return "0"
            raise ExpectError("符号不可求值：%r（在 %r）" % (name, expr))

        e2 = re.sub(r"(?<![0-9A-Za-z_])[A-Za-z_][A-Za-z0-9_.]*"
                    r"(?![0-9A-Za-z_])", repl, e)
        e2 = e2.replace("/", "//")
        try:
            return int(eval(e2, {"__builtins__": {}}, {})) & 0xFFFFFFFFFFFFFFFF
        except Exception as exc:
            raise ExpectError("表达式求值失败：%r → %r（%s）" % (expr, e2, exc))

    # ---- 宏 ----
    def _substitute(self, text, args, vararg):
        def repl(m):
            name = m.group(1)
            if name == "@":
                return "1"
            if name in args:
                return args[name]
            if vararg is not None and name == vararg[0]:
                return vararg[1]
            return m.group(0)
        return re.sub(r"\\([A-Za-z_@][A-Za-z0-9_@]*)", repl, text)

    def call_macro(self, name, argtext, origin):
        mac = self.macros[name]
        vals = _split_args(argtext) if argtext.strip() else []
        args, vararg, pos = {}, None, 0
        for pname, default, isvar in mac[1]:
            if isvar:
                vararg = (pname, ", ".join(vals[pos:]) if pos < len(vals) else "")
                pos = len(vals)
                continue
            if pos < len(vals):
                args[pname] = vals[pos]
                pos += 1
            elif default is not None:
                args[pname] = default
            else:
                args[pname] = ""      # GNU as：缺参展开为空（宏内 `.ifnb` 判空）
        old = self.cur_macro
        self.cur_macro = name
        try:
            self.run_block(mac[2], origin, args, vararg, True)
        finally:
            self.cur_macro = old

    # ---- 条件 ----
    def _cond(self, kind, rest):
        parts = _split_args(rest)
        if kind in ("ifc", "ifnc"):
            eq = len(parts) == 2 and parts[0] == parts[1]
            return eq if kind == "ifc" else not eq
        if kind == "ifnb":
            return bool(parts and parts[0] != "")
        if kind == "ifb":
            return not (parts and parts[0] != "")
        if kind in ("ifdef", "ifndef"):
            name = parts[0] if parts else ""
            got = name in self.macros or name in self.symbols
            return got if kind == "ifdef" else not got
        return self.ev(rest) != 0

    def run_file(self, path: Path):
        recs = list(enumerate(path.read_text(encoding="utf-8").splitlines(), 1))
        self.run_block(recs, (str(path), 0), {}, None, False)

    def run_block(self, records, origin, args, vararg, fixed):
        self.depth += 1
        if self.depth > 64:
            raise ExpectError("宏展开过深（%s:%s）" % (self._rel(origin[0]), origin[1]))
        stack = []
        i = 0
        try:
            while i < len(records):
                lineno, raw = records[i]
                i += 1
                s = self._substitute(_strip_comment(raw), args, vararg).strip()
                if not s:
                    continue
                here = origin if fixed else (origin[0], lineno)
                if s.startswith("."):
                    bits = s.split(None, 1)
                    head = bits[0]
                    rest = bits[1].strip() if len(bits) > 1 else ""
                    if head in (".ifc", ".ifnc", ".ifnb", ".ifb", ".ifdef",
                                ".ifndef", ".if"):
                        parent = all(x["active"] for x in stack)
                        entry = {"active": False, "taken": False}
                        stack.append(entry)
                        cond = self._cond(head[1:], rest) if parent else False
                        entry["active"] = parent and cond
                        entry["taken"] = entry["active"]
                        continue
                    if head == ".else":
                        if not stack:
                            raise ExpectError(".else 无配对（%s）" % (self._where(here),))
                        top = stack[-1]
                        parent = all(x["active"] for x in stack[:-1])
                        top["active"] = parent and not top["taken"]
                        top["taken"] = top["taken"] or top["active"]
                        continue
                    if head == ".endif":
                        if not stack:
                            raise ExpectError(".endif 无配对（%s）" % (self._where(here),))
                        stack.pop()
                        continue
                    if not all(x["active"] for x in stack):
                        continue
                    if head == ".macro":
                        body, i = self._collect(records, i, ".endm")
                        self._define_macro(rest, body, here)
                        continue
                    if head in (".rept", ".irp"):
                        body, i = self._collect(records, i, ".endr")
                        if head == ".rept":
                            for _ in range(self.ev(rest)):
                                self.run_block(body, here, args, vararg, True)
                        else:
                            parts = _split_args(rest)
                            for v in parts[1:]:
                                a2 = dict(args)
                                a2[parts[0]] = v
                                self.run_block(body, here, a2, vararg, True)
                        continue
                    if head in (".equ", ".set"):
                        parts = _split_args(rest)
                        name = parts[0].strip()
                        val = self.ev(parts[1])
                        if name == "__NCHECK":
                            self._ncheck(val, here)
                        else:
                            self.symbols[name] = val
                        continue
                    if head == ".include":
                        self._include(rest.strip().strip('"'), here)
                        continue
                    if head in (".section", ".pushsection"):
                        self.section = rest.split(",")[0].strip().strip('"')
                        continue
                    if head == ".popsection":
                        self.section = None
                        continue
                    if head in (".dd.o64", ".dd.t32", ".dd.w16", ".dd.b08",
                                ".space", ".p2align"):
                        self._data(head, rest, here)
                        continue
                    continue
                if not all(x["active"] for x in stack):
                    continue
                self._insn(s, here)
        finally:
            self.depth -= 1

    def _where(self, here):
        return "%s:%s" % (self._rel(here[0]), here[1])

    def _rel(self, p):
        try:
            return str(Path(p).resolve().relative_to(self.root))
        except ValueError:
            return str(p)

    def _collect(self, records, i, end):
        out, depth = [], 0
        while i < len(records):
            lineno, raw = records[i]
            i += 1
            s = _strip_comment(raw).strip()
            if s.startswith((".macro", ".rept", ".irp")):
                depth += 1
            if s.startswith(end) and depth == 0:
                break
            if s.startswith((".endm", ".endr")):
                depth -= 1
            out.append((lineno, raw))
        return out, i

    def _define_macro(self, rest, body, here):
        bits = rest.split(None, 1)
        name = bits[0] if bits else ""
        prest = bits[1] if len(bits) > 1 else ""
        params = []
        for p in _split_args(prest):
            default, var = None, False
            if ":" in p:
                p, mode = p.split(":", 1)
                if mode.strip() == "vararg":
                    var = True
            if "=" in p:
                p, default = p.split("=", 1)
            params.append((p.strip(), default, var))
        if not name:
            raise ExpectError("空宏名（%s）" % (self._where(here),))
        self.macros[name] = (name, params, body)

    def _include(self, rel, here):
        path = (self.root / rel).resolve()
        if not path.is_file():
            raise ExpectError(".include 目标不存在：%s（%s）"
                              % (rel, self._where(here)))
        recs = list(enumerate(path.read_text(encoding="utf-8").splitlines(), 1))
        self.run_block(recs, (str(path), 0), {}, None, False)

    def _data(self, head, rest, here):
        if self.section != ".testdata":
            return
        buf = self.sections.setdefault(".testdata", bytearray())
        if head == ".space":
            buf.extend(b"\x00" * self.ev(_split_args(rest)[0]))
        elif head == ".p2align":
            n = self.ev(_split_args(rest)[0])
            while len(buf) % (1 << n):
                buf.append(0)
        else:
            width = {".dd.o64": 8, ".dd.t32": 4, ".dd.w16": 2, ".dd.b08": 1}[head]
            for v in [self.ev(a) for a in _split_args(rest) if a]:
                buf.extend(int(v).to_bytes(width, "big"))

    def _ncheck(self, val, here):
        """`__NCHECK` 加一 ⇒ 新槽。槽数与 dump 长度同源（收尾按 `__NCHECK` 输出）。"""
        self.symbols["__NCHECK"] = val
        if val == len(self.slots):
            return                    # 同一槽重复 `.set`（无）
        for _ in range(val - len(self.slots)):
            slot = self.pending or {
                "kind": "unwritten", "value": None, "expr": "-",
                "detail": "检查点无 SIGUPD 写入口", "source": self._where(here),
            }
            self.slots.append(slot)
            self.pending = None

    def _insn(self, ins, here):
        bits = ins.split(None, 1)
        head = bits[0]
        rest = bits[1].strip() if len(bits) > 1 else ""
        if head.endswith(":"):
            return
        mnem = head.lower()
        parts = _split_args(rest)
        if mnem in ("set.rd", "set.rb") and len(parts) >= 2:
            self.regs[parts[0]] = ("const", parts[1], None)
        elif mnem == "ld.o" and len(parts) >= 2:
            m = re.match(r"\[\s*([A-Za-z0-9]+)\s*,\s*(.+)\]$", parts[1])
            base = self.regs.get(m.group(1)) if m else None
            if m and base and base[0] == "const":
                self.regs[parts[0]] = ("mem", "(%s)+(%s)" % (base[1], m.group(2)),
                                       base[1])
            else:
                self.regs[parts[0]] = ("unk", None, None)
        elif mnem == "sigupd":
            self._record(parts[0] if parts else "?", here)
            self.regs = {}
        elif head in self.macros:
            self.call_macro(head, rest, here)

    def _record(self, reg, here):
        exp = self.regs.get("rd20")
        if exp and exp[0] == "const":
            self.pending = {"kind": "value", "value": self.ev(exp[1]),
                            "expr": exp[1], "detail": "",
                            "source": self._where(here)}
        elif exp and exp[0] == "mem" and str(exp[2]).strip().startswith("WDATA"):
            addr = self.ev(exp[1])
            self.pending = {"kind": "table", "value": ("@", addr),
                            "expr": exp[1],
                            "detail": "WDATA 数据区（独立 oracle）",
                            "source": self._where(here)}
        else:
            macro = self.cur_macro or "-"
            self.pending = {"kind": "relation", "value": None, "expr": "-",
                            "detail": "运行期关系断言（%s）" % macro,
                            "source": self._where(here)}

    def finish(self):
        if self.pending is not None:
            raise ExpectError("最后一条 __REC 之后没有 __NCHECK 加一（%s）"
                              % (self.pending.get("source"),))


