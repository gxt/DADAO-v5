#!/usr/bin/env python3
"""inst_expected.py — 从 `tests/inst/**/*.S` 派生「槽 → 期望值」序列（m17-testcases-001）。

**期望值来源**（单一真源，不从实现反推）
------------------------------------
`tests/inst` 的每个镜像（每 `.S` 一个）在链例里逐个检查点调用 `__CHECK_*` 宏；
宏体把**内联期望常量**装进 `rd20`，`__REC`/`SIGUPD` 再把实测值写进签名槽
（`tests/shared/asm/signature.inc`）。本模块把 `.S` + 宏层（`inst_test.inc`、
各册 `<册>.inc`、`.S` 内文件专用宏）按**汇编语义**展开，取每个检查点的期望：

  * `value`     —— `__CHECK_RD/__CHECK_MEM` 的 `exp` 是 `.S` 里的内联常量
                   （表达式的符号 `ENTRY`/`TEST_DATA`/… 按链接布局与宏层 `.equ` 求值）；
  * `table`     —— `_MEM` 变体的期望从 `.testdata` 的 `WDATA` 表装载（独立 oracle：
                   期望值来自数据区字面量，不经被测指令）；
  * `relation`  —— 期望是**运行期关系**（如 `__CHECK_RD_IP` 的「两次读回相等」、
                   `__CHECK_MEM_RB` 的「内存 == 运行期寄存器」）⇒ 没有静态常量，
                   门控**不比对取值**（语义由 `.S` 内 `br.eq` 承担；写入口存在性
                   由本模块的静态派生保证）；
  * `unwritten` —— 源码里该检查点没有写槽入口（`__NCHECK` 加一但无 `SIGUPD`）
                   ⇒ 门控按「槽 N 未写」判红（漏跑可见）。

槽数 = `__NCHECK` 的现场累加（= 收尾 `SIG_DUMP_CHARS TEST_BUF, __NCHECK` 的槽数），
**不写死**；镜像集 = `tests/inst/` 下含 `.S` 的册目录（现场派生）。

数据产物（`tests/data/inst-signature/`，`render_*` 生成，勿手改）
  * `expected.tsv`     —— `image/slot/kind/expected/expr/source` 六列；
  * `inputs.sha256`    —— 派生所读的全部输入（`.S` + 宏层 + 链接布局）的 sha256；
  * `README.md`        —— 三件套说明（输入清单 / 生成命令 / 为何可入库）。

对外的派生入口：`derive(root)` → `list[Image]`；`render_expected/render_inputs`
→ 文本；`write_data(root)` 落盘。门控 = `tools/testcases/inst/check_inst_sig.py`。
"""
