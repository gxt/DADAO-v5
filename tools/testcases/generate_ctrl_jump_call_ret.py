# ── jump-iiii (unchanged) ─────────────────────────────────────────────
def _gen_jump_iiii():
    op = int(BY_KEY[("jump_iiii_rb", "iiii")]["op"], 16)
    word = _build_word_iiii(op, IMM)
    boundary_imm = (-0x1000) & 0xFFFFFF
    boundary_word = _build_word_iiii(op, boundary_imm)
    imm_s = boundary_imm - (1 << 24) if boundary_imm & (1 << 23) else boundary_imm
    target_boundary = "0x%012X" % ((RB0 + (imm_s << 2)) & 0xFFFFFFFFFFFF)
    return [
        _case("encoding", "jump_iiii_rb", "iiii", word, {}, None,
              None, None, SC_JUMP,
              "encoding: word matches opcodes.yaml mask/value, imms24=2 "
              "(non-zero, non-self-jump)"),
        _case("semantic", "jump_iiii_rb", "iiii", word, {}, {},
              None, TARGET, SC_JUMP,
              "semantic: rb0=0xFFFF00000000 (RAM entry, ADR-0004 D2.2), "
              "imms24=2, Addr=rb0+(imms24<<2)=0xFFFF00000000+8="
              "0xFFFF00000008; no state change"),
        _case("boundary", "jump_iiii_rb", "iiii", boundary_word, {}, {},
              "UNMAPPED", None, SC_JUMP_LEG,
              "boundary UNMAPPED: imms24=-0x1000, "
              "target=rb0+(imms24<<2)=0x%012X+(-0x4000)=0x%012X → "
              "beyond RAM (0xFFFF_00FF_FFFF) → UNMAPPED (0x87)"
              % (RB0, int(target_boundary, 16))),
    ]


# ── jump-rrii (unchanged) ─────────────────────────────────────────────
def _gen_jump_rrii():
    op = int(BY_KEY[("jump_rrii_rb", "rrii")]["op"], 16)
    enc_word = _build_word_rrii(op, 0, 0, IMM)
    unmapped_word = _build_word_rrii(op, 3, 0, 0)
    return [
        _case("encoding", "jump_rrii_rb", "rrii", enc_word, {}, None,
              None, None, SC_JUMP,
              "encoding: word matches opcodes.yaml mask/value, rbha=rb0 "
              "(index 0), rdhb=rd0 (index 0), imms12=2"),
        _case("semantic", "jump_rrii_rb", "rrii", enc_word, {}, {},
              None, TARGET, SC_JUMP,
              "semantic: rb0=0xFFFF00000000, rd0=0, imms12=2, "
              "Addr=rb0+rd0+(imms12<<2)=0xFFFF00000000+0+8="
              "0xFFFF00000008; no state change"),
        _case("legality", "jump_rrii_rb", "rrii", unmapped_word,
              {"rb": {"rb3": "0x0000000000000000"}}, None,
              "UNMAPPED", None, SC_JUMP_LEG,
              "legality UNMAPPED: rbha=rb3=0, rdhb=rd0=0, imms12=0 → "
              "addr=0 → unmapped (0x87), ADR-0004 D5.6"),
    ]


# ── call-iiii (D7 rewrite) ───────────────────────────────────────────
def _gen_call_iiii():
    op = int(BY_KEY[("call_iiii_ra", "iiii")]["op"], 16)
    word = _build_word_iiii(op, IMM)

    # C1: cold RA → push new entry, RACNT=1
    #   ra0: RACNT 0→1, MRPTR stays 0
    #   ra63: [63:48]=1, [47:0]=PC+4
    c1_out_ra0 = _ra0(1, 0)
    c1_out_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))

    # C2: recursive → count +1, RACNT unchanged
    #   input: ra0 has RACNT=1, MRPTR=0; ra63 has count=1, addr=PC+4
    #   output: ra63 count=2, addr=PC+4; ra0 unchanged (RACNT stays 1)
    c2_in_ra0 = _ra0(1, 0)
    c2_in_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))
    c2_out_ra63 = RA64_FMT % ((2 << 48) | (RB0 + 4))

    # C3a: shift-push → new entry, RACNT += 1
    #   input: RACNT=1, ra63 count=1, addr=0xAAAA00000000
    #   output: RACNT=2, ra63=[1, PC+4], ra62=[1, 0xAAAA00000000]
    c3a_in_ra0 = _ra0(1, 0)
    c3a_in_ra63 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)
    c3a_out_ra0 = _ra0(2, 0)
    c3a_out_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))
    c3a_out_ra62 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)

    # RASOF: RACNT=63, MRPTR=0, different address → C3b → RASOF
    rasof_in_ra0 = _ra0(63, 0)
    # ra63 has a valid entry (count=1, some address) so C2 doesn't match
    rasof_in_ra63 = RA64_FMT % ((1 << 48) | 0xCCCC_0000_0000)

    # C3b MemRAS: RACNT=63, MRPTR!=0 → spill oldest to MemRAS, RACNT stays 63
    #   Oldest entry = ra[64-RACNT] = ra[64-63] = ra1
    #   ra1 has count=5, addr=0xDDDD00000000
    #   Spill ra1 to MRPTR-8, then push new entry, MRPTR-=8
    c3b_mrptr = MRPTR_BASE
    c3b_mrptr_after = "0x%012X" % (c3b_mrptr - 8)
    c3b_in_ra0 = _ra0(63, c3b_mrptr)
    c3b_in_ra1 = RA64_FMT % ((5 << 48) | 0xDDDD_0000_0000)
    c3b_in_ra63 = RA64_FMT % ((1 << 48) | 0xCCCC_0000_0000)
    c3b_out_ra0 = _ra0(63, c3b_mrptr - 8)
    c3b_out_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))
    c3b_mem_addr = c3b_mrptr_after
    c3b_mem_val = RA64_FMT % ((5 << 48) | 0xDDDD_0000_0000)

    # Build input dict for RASOF (all 63 ra entries with RACNT=63)
    # Only need ra0 + ra63 in input (RACNT determines validity)
    rasof_inp = {"ra": {"ra0": rasof_in_ra0, "ra63": rasof_in_ra63}}

    # Build input dict for C3b MemRAS
    c3b_inp = {"ra": {"ra0": c3b_in_ra0, "ra1": c3b_in_ra1, "ra63": c3b_in_ra63}}

    return [
        _case("encoding", "call_iiii_ra", "iiii", word, {}, None,
              None, None, SC_CALL,
              "encoding: word matches opcodes.yaml mask/value, imms24=2 "
              "(non-zero, non-self-call)"),
        # C1: cold RA → new address pushed, RACNT 0→1
        _case("semantic", "call_iiii_ra", "iiii", word, {},
              {"ra": {"ra0": c1_out_ra0, "ra63": c1_out_ra63}},
              None, TARGET, SC_CALL_C1,
              "semantic C1: rb0=0xFFFF00000000, imms24=2, "
              "Addr=0xFFFF00000008; cold RA (RACNT=0, MRPTR=0); "
              "push: ra63=[count=1, ret_addr=0xFFFF00000004], RACNT→1; "
              "ra0=%s" % c1_out_ra0),
        # C2: recursive → count +1
        _case("semantic", "call_iiii_ra", "iiii", word,
              {"ra": {"ra0": c2_in_ra0, "ra63": c2_in_ra63}},
              {"ra": {"ra63": c2_out_ra63}},
              None, TARGET, SC_CALL_C2,
              "semantic C2 (recursive fold): ra0=%s, ra63 input "
              "[count=1, addr=0xFFFF00000004]; PC+4=0xFFFF00000004 == "
              "ra63[47:0] → count+1: ra63=[count=2, addr=0xFFFF00000004]; "
              "RACNT unchanged (1)" % c2_in_ra0),
        # C3a: shift-push
        _case("semantic", "call_iiii_ra", "iiii", word,
              {"ra": {"ra0": c3a_in_ra0, "ra63": c3a_in_ra63}},
              {"ra": {
                  "ra0": c3a_out_ra0,
                  "ra63": c3a_out_ra63,
                  "ra62": c3a_out_ra62,
              }},
              None, TARGET, SC_CALL_C3a,
              "semantic C3a (shift-push): ra0=%s, ra63 input "
              "[count=1, addr=0xAAAA00000000]; PC+4=0xFFFF00000004 ≠ "
              "ra63[47:0] → shift-push: new ra63=[1, 0xFFFF00000004], "
              "old ra63→ra62=[1, 0xAAAA00000000]; RACNT→2, ra0=%s"
              % (c3a_in_ra0, c3a_out_ra0)),
        # RASOF: RACNT=63, MRPTR=0 → overflow with no MemRAS
        _case("legality", "call_iiii_ra", "iiii", word,
              rasof_inp, None,
              "RASOF", None, SC_CALL_RASOF,
              "legality RASOF: ra0=%s (RACNT=63, MRPTR=0); "
              "ra63=[count=1, addr=0xCCCC00000000]; PC+4=0xFFFF00000004 ≠ "
              "ra63[47:0] → C3b: RACNT==63, MRPTR==0 → RASOF (0x8A)"
              % rasof_in_ra0),
        # C3b MemRAS: RACNT=63, MRPTR!=0 → spill oldest to MemRAS
        _case("semantic", "call_iiii_ra", "iiii", word,
              c3b_inp,
              {"ra": {
                  "ra0": c3b_out_ra0,
                  "ra63": c3b_out_ra63,
              },
               "memory": [{
                   "address": c3b_mem_addr,
                   "value": c3b_mem_val,
               }]},
              None, TARGET, SC_CALL_C3b_MEM,
              "semantic C3b (MemRAS spill): ra0=%s (RACNT=63, MRPTR=0x%X); "
              "ra1=[count=5, addr=0xDDDD00000000] (oldest, idx=64-63=1); "
              "ra63=[count=1, addr=0xCCCC00000000]; PC+4=0xFFFF00000004 ≠ "
              "ra63[47:0] → C3b: MRPTR-=8→%s, spill ra1→MemRAS[%s], "
              "push new ra63=[1, 0xFFFF00000004]; RACNT stays 63"
              % (c3b_in_ra0, c3b_mrptr, c3b_mrptr_after, c3b_mem_addr)),
    ]


