#!/usr/bin/env python3
"""Generate ctrl-jump.yaml, ctrl-call.yaml, ctrl-ret.yaml.

Covers M1 identities (jump-iiii, jump-rrii, call-iiii, call-rrii, ret-riii) with:
  - encoding cases (jump/call only; ret-riii excluded: return target depends on harness layout)
  - semantic/boundary cases with expected_pc, expected_state (ra + memory)
  - legality cases (UNMAPPED, RASOF, RASUF)

Spec-first: all encoding words, expected values, and spec_cite derived from
contracts/opcodes.yaml, spec/SimRISC-00 §返回地址栈 (D7),
spec/SimRISC-06 §函数调用|§函数返回, and
.tao/adr/adr-0004-test-machine.md (D2.1, D5.5, D5.6, D6.5).

RA semantics (ADR-0012 D7):
  - ra0[53:48] = RACNT (valid entry count, 0–63); ra0[47:0] = MRPTR (MemRAS top address, 0=no MemRAS)
  - ra1–ra63: [63:48] = recursive count, [47:0] = return address; ra63 = stack top
  - Validity determined by RACNT, NOT by individual entry values
  - Full-stack overflow: RACNT==63, MRPTR==0 → RASOF; MRPTR!=0 → spill oldest to MemRAS, keep RACNT=63
  - Pop underflow: RACNT==0, MRPTR==0 → RASUF; RACNT==0, MRPTR!=0 → read MemRAS entry

PC convention: instruction address = 0xffff_0000_0000 (RAM entry, ADR-0004 D2.2).
imm=2 for jump/call → target = rb0 + 8 = 0xffff00000008.
Return address for call = PC+4 = 0xffff00000004.
"""

import os
import sys

try:
    import yaml
except ImportError:
    sys.exit("ERROR: PyYAML 未安装。运行: pip install pyyaml")

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(REPO, "tests", "vectors", "isa")

# ── Load opcodes (for validation only) ────────────────────────────────
with open(os.path.join(REPO, "contracts", "opcodes.yaml")) as f:
    ALL = yaml.safe_load(f)

BY_KEY = {}
for r in ALL:
    if not r.get("excluded_m1"):
        BY_KEY[(r["id"], r["format"])] = r

# ── Constants ─────────────────────────────────────────────────────────
RB0 = 0xFFFF_0000_0000          # instruction address (ADR-0004 D2.2/D6.5)
IMM = 2                         # imm for jump/call (not 0, not 1)
TARGET = "0x%012X" % (RB0 + (IMM << 2))     # 0xFFFF00000008
RETURN_ADDR = "0x%012X" % (RB0 + 4)          # 0xFFFF00000004
RA64_FMT = "0x%016X"            # 64-bit hex for RA registers
HEX48_FMT = "0x%012X"           # 48-bit hex for MRPTR / addresses

# MemRAS test addresses (in RAM, 8-byte aligned, within 0xFFFF00000000–0xFFFF00FFFFFF)
MRPTR_BASE = 0xFFFF_00F0_0000   # MemRAS base for test cases (within RAM window)

# ── ra0 helpers (D7 bit layout) ───────────────────────────────────────
def _ra0(racnt, mrptr):
    """Encode ra0: [53:48]=RACNT, [47:0]=MRPTR."""
    return RA64_FMT % ((racnt & 0x3F) << 48 | (mrptr & 0xFFFFFFFFFFFF))


# ── Encoding word builders ────────────────────────────────────────────
def _build_word_iiii(op, imm24):
    """iiii format: op[31:24] | imms24[23:0]."""
    return (op << 24) | (imm24 & 0xFFFFFF)

def _build_word_rrii(op, ha, hb, imm12):
    """rrii format: op[31:24] | ha[23:18] | hb[17:12] | imms12[11:0]."""
    return (op << 24) | (ha << 18) | (hb << 12) | (imm12 & 0xFFF)

def _build_word_riii(op, ha, imm18):
    """riii format: op[31:24] | ha[23:18] | imms18[17:0]."""
    return (op << 24) | (ha << 18) | (imm18 & 0x3FFFF)

def _hex8(w):
    """Format 32-bit word as 0x-prefixed uppercase 8-char hex."""
    return "0x%08X" % w

# ── Case factory ──────────────────────────────────────────────────────
def _case(cls, insn, fmt, word, inp, out, fault=None,
          expected_pc=None, spec_cite="", notes=""):
    # Extract mnemonic from new id format: mnemonic_format_bank
    if '_' in insn:
        _FORMATS = ('orrr', 'orri', 'rrrr', 'riii', 'rrii', 'rwii', 'iiii', 'rrri', 'oiii')
        parts = insn.split('_')
        if len(parts) >= 3 and parts[-2] in _FORMATS:
            mnem = '_'.join(parts[:-2])
        else:
            mnem = parts[0]
    else:
        mnem = insn.split("-")[0]
    return {
        "class": cls,
        "deferred_reason": None,
        "encoding": {"word": _hex8(word)},
        "expected_fault": fault,
        "expected_pc": expected_pc,
        "expected_state": out,
        "format": fmt,
        "input_state": inp,
        "id": insn,
        "mnemonic": mnem,
        "notes": notes,
        "spec_cite": spec_cite,
        "status": "active",
    }


