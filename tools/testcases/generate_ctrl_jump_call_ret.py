# ── ret-riii (D7 rewrite) ────────────────────────────────────────────
def _gen_ret_riii():
    op = int(BY_KEY[("ret_riii_ra", "riii")]["op"], 16)
    word = _build_word_riii(op, 0, 0)  # rdha=rd0, imms18=0

    # D2: RACNT>0, count>1 → decrement count, RACNT unchanged
    #   input: RACNT=2, ra63=[count=3, addr=PC+4]
    #   output: ra63=[count=2, addr=PC+4]; RACNT stays 2
    d2_in_ra0 = _ra0(2, 0)
    d2_in_ra63 = RA64_FMT % ((3 << 48) | (RB0 + 4))
    d2_out_ra63 = RA64_FMT % ((2 << 48) | (RB0 + 4))

    # D3: RACNT>0, count==1 → pop stack top, RACNT -= 1
    #   input: RACNT=2, ra63=[count=1, addr=PC+4], ra62=[count=1, addr=0xAAAA00000000]
    #   output: ra63=[count=1, addr=0xAAAA00000000] (shifted from ra62), RACNT→1
    d3_in_ra0 = _ra0(2, 0)
    d3_in_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))
    d3_in_ra62 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)
    d3_out_ra0 = _ra0(1, 0)
    d3_out_ra63 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)

    # D4b cnt>1: RACNT==0, MRPTR!=0, MemRAS entry count>1 → push to stack, RACNT=1
    #   MemRAS entry: count=3, addr=0xBBBB00000000 at MRPTR
    #   After: count-1=2, pushed to ra63, MRPTR+=8, RACNT=1
    #   PC = entry[47:0] = 0xBBBB00000000
    d4b_mrptr = MRPTR_BASE
    d4b_mrptr_after = "0x%012X" % (d4b_mrptr + 8)
    d4b_in_ra0 = _ra0(0, d4b_mrptr)
    d4b_mem_in = RA64_FMT % ((3 << 48) | 0xBBBB_0000_0000)
    d4b_out_ra0 = _ra0(1, d4b_mrptr + 8)
    d4b_out_ra63 = RA64_FMT % ((2 << 48) | 0xBBBB_0000_0000)
    d4b_pc = HEX48_FMT % 0xBBBB_0000_0000  # PC = entry[47:0]

    # D4b cnt=1: RACNT==0, MRPTR!=0, MemRAS entry count=1 → consume, no push
    #   MemRAS entry: count=1, addr=0xCCCC00000000 at MRPTR
    #   After: PC=entry[47:0], MRPTR+=8, RACNT stays 0, no RegRAS change
    d4b1_mrptr = MRPTR_BASE
    d4b1_mrptr_after = "0x%012X" % (d4b1_mrptr + 8)
    d4b1_in_ra0 = _ra0(0, d4b1_mrptr)
    d4b1_mem_in = RA64_FMT % ((1 << 48) | 0xCCCC_0000_0000)
    d4b1_out_ra0 = _ra0(0, d4b1_mrptr + 8)
    d4b1_pc = HEX48_FMT % 0xCCCC_0000_0000  # PC = entry[47:0]

    # D4b cnt=0: RACNT==0, MRPTR!=0, MemRAS entry count=0 → RASUF
    d4b0_in_ra0 = _ra0(0, d4b_mrptr)
    d4b0_mem_in = RA64_FMT % ((0 << 48) | 0xEEEE_0000_0000)

    # D4a: RACNT==0, MRPTR==0 → RASUF
    d4a_in_ra0 = _ra0(0, 0)

    # TESTCASES-022t: ret rd1, 42 → normal pop (mirrors D3) + rd1 = sign_extend(42)
    rd1_in_ra0 = _ra0(2, 0)
    rd1_in_ra63 = RA64_FMT % ((1 << 48) | (RB0 + 4))
    rd1_in_ra62 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)
    rd1_out_ra0 = _ra0(1, 0)
    rd1_out_ra63 = RA64_FMT % ((1 << 48) | 0xAAAA_0000_0000)
    rd1_word = _build_word_riii(op, 1, 42)          # 0x7604002A
    rd1_value = RA64_FMT % 42                       # sign_extend(42) = 0x2A

    return [
        # D2: decrement recursive count
        _case("semantic", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d2_in_ra0, "ra63": d2_in_ra63}},
              {"ra": {"ra63": d2_out_ra63}},
              None, RETURN_ADDR, SC_RET_D2,
              "semantic D2 (count>1): ra0=%s, ra63=[count=3, "
              "addr=0xFFFF00000004]; ret → PC=ra63[47:0]=0xFFFF00000004; "
              "count 3→2, RACNT unchanged (2); ra63=[count=2, "
              "addr=0xFFFF00000004]" % d2_in_ra0),
        # D3: pop stack top (count==1)
        _case("semantic", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d3_in_ra0, "ra63": d3_in_ra63,
                       "ra62": d3_in_ra62}},
              {"ra": {"ra0": d3_out_ra0, "ra63": d3_out_ra63}},
              None, RETURN_ADDR, SC_RET_D3,
              "semantic D3 (count=1, pop): ra0=%s, ra63=[count=1, "
              "addr=0xFFFF00000004], ra62=[count=1, addr=0xAAAA00000000]; "
              "ret → PC=0xFFFF00000004; count=1 → pop: shift-down, "
              "ra62→ra63=[count=1, addr=0xAAAA00000000]; RACNT→1, ra0=%s"
              % (d3_in_ra0, d3_out_ra0)),
        # D4b cnt>1: restore from MemRAS, push to stack
        _case("semantic", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d4b_in_ra0},
               "memory": [{"address": "0x%012X" % d4b_mrptr,
                           "value": d4b_mem_in}]},
              {"ra": {"ra0": d4b_out_ra0, "ra63": d4b_out_ra63}},
              None, d4b_pc, SC_RET_D4b,
              "semantic D4b (MemRAS count>1): ra0=%s (RACNT=0, MRPTR=0x%X); "
              "MemRAS[MRPTR]=[count=3, addr=0xBBBB00000000]; "
              "ret → PC=条目[47:0]=0xBBBB00000000; count>1→push to stack: "
              "ra63=[count=2, addr=0xBBBB00000000], MRPTR+=8→%s, RACNT=1"
              % (d4b_in_ra0, d4b_mrptr, d4b_mrptr_after)),
        # D4b cnt=1: restore from MemRAS, consume (no push)
        _case("semantic", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d4b1_in_ra0},
               "memory": [{"address": "0x%012X" % d4b1_mrptr,
                           "value": d4b1_mem_in}]},
              {"ra": {"ra0": d4b1_out_ra0}},
              None, d4b1_pc, SC_RET_D4b,
              "semantic D4b (MemRAS count=1): ra0=%s (RACNT=0, MRPTR=0x%X); "
              "MemRAS[MRPTR]=[count=1, addr=0xCCCC00000000]; "
              "ret → PC=条目[47:0]=0xCCCC00000000; count=1→consume: "
              "MRPTR+=8→%s, RACNT stays 0; no RegRAS change"
              % (d4b1_in_ra0, d4b1_mrptr, d4b1_mrptr_after)),
        # D4b cnt=0: MemRAS entry count=0 → RASUF
        _case("legality", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d4b0_in_ra0},
               "memory": [{"address": "0x%012X" % d4b_mrptr,
                           "value": d4b0_mem_in}]},
              None,
              "RASUF", None, SC_RET_D4B_RASUF,
              "legality D4b RASUF (MemRAS count=0): ra0=%s (RACNT=0, "
              "MRPTR=0x%X); MemRAS[MRPTR]=[count=0, addr=0xEEEE00000000]; "
              "ret → read MemRAS: count=0 → RASUF (0x8B)"
              % (d4b0_in_ra0, d4b_mrptr)),
        # D4a: RACNT==0, MRPTR==0 → RASUF (cold RA)
        _case("legality", "ret_riii_ra", "riii", word,
              {"ra": {"ra0": d4a_in_ra0}}, None,
              "RASUF", None, SC_RET_RASUF,
              "legality D4a RASUF: ra0=%s (RACNT=0, MRPTR=0); "
              "ret → D4: RACNT==0, MRPTR==0 → RASUF (0x8B)" % d4a_in_ra0),
        # ── TESTCASES-022t: ret rd0 ⇒ imms18 MUST be 0 (dst_rd0_nonzero) ──
        # rdha=rd0, imms18=1 (≠0) → ILLI
        _case("legality", "ret_riii_ra", "riii", _build_word_riii(op, 0, 1),
              {}, None,
              "ILLI", None, SC_RET_RD0_IMMS18,
              "legality dst_rd0_nonzero: rdha=rd0, imms18=1 (≠0) → ILLI (0x88); "
              "word=0x76<<24|0<<18|1=0x76000001"),
        # rdha=rd0, imms18=-1 (0x3FFFF, ≠0) → ILLI
        _case("legality", "ret_riii_ra", "riii",
              _build_word_riii(op, 0, -1 & 0x3FFFF),
              {}, None,
              "ILLI", None, SC_RET_RD0_IMMS18,
              "legality dst_rd0_nonzero: rdha=rd0, imms18=-1 (0x3FFFF, ≠0) → "
              "ILLI (0x88); word=0x76<<24|0<<18|0x3FFFF=0x7603FFFF"),
        # rdha=rd1 (≠rd0), imms18=42 → legal; normal pop (mirrors D3) + rd1 write
        _case("semantic", "ret_riii_ra", "riii", rd1_word,
              {"ra": {"ra0": rd1_in_ra0, "ra63": rd1_in_ra63,
                       "ra62": rd1_in_ra62}},
              {"rd": {"rd1": rd1_value},
               "ra": {"ra0": rd1_out_ra0, "ra63": rd1_out_ra63}},
              None, RETURN_ADDR, SC_RET_RD0_IMMS18,
              "semantic ret rd1, 42 (rdha=rd1≠rd0, unconstrained): ra0=%s, "
              "ra63=[count=1, addr=0xFFFF00000004], ra62=[count=1, "
              "addr=0xAAAA00000000]; ret → PC=0xFFFF00000004; count=1 → pop: "
              "ra62→ra63=[count=1, addr=0xAAAA00000000], RACNT→1 (ra0=%s); "
              "rd1 = sign_extend(42) = 0x2A"
              % (rd1_in_ra0, rd1_out_ra0)),
    ]


# ── Write YAML ────────────────────────────────────────────────────────
def _write_yaml(filename, header, cases):
    path = os.path.join(OUT_DIR, filename)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(path, "w") as f:
        f.write(header)
        yaml.dump(cases, f, default_flow_style=False, allow_unicode=True,
                  width=120)
    n_enc = sum(1 for c in cases if c["class"] == "encoding")
    n_sem = sum(1 for c in cases if c["class"] == "semantic")
    n_leg = sum(1 for c in cases if c["class"] == "legality")
    print("Wrote %s: %d cases (%d encoding, %d semantic, %d legality)" % (
        path, len(cases), n_enc, n_sem, n_leg))


# ── Main ──────────────────────────────────────────────────────────────
def main():
    jump_cases = _gen_jump_iiii() + _gen_jump_rrii()
    call_cases = _gen_call_iiii() + _gen_call_rrii()
    ret_cases = _gen_ret_riii()

    _write_yaml("ctrl-jump.yaml", HEADER_JUMP, jump_cases)
    _write_yaml("ctrl-call.yaml", HEADER_CALL, call_cases)
    _write_yaml("ctrl-ret.yaml", HEADER_RET, ret_cases)

    total = len(jump_cases) + len(call_cases) + len(ret_cases)
    print("\nTotal: %d cases across 3 files" % total)
    print("Identities covered: jump-iiii, jump-rrii, call-iiii, call-rrii, ret-riii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
