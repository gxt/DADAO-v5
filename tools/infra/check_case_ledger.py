#!/usr/bin/env python3
"""check_case_ledger.py — 用例/pattern 级「删除哨兵」（INFRA-102t；ISS-102+ISS-118 合并）。

问题（两条 issue 的共同内核）
------------------------------
* `ISS-102`：向量覆盖门控是 `(id, class)` 粒度（「至少 1 条 active 用例」）——
  删掉同一 `(id, class)` 的第 2 条用例不触发任何报错；
* `ISS-118`：lit 覆盖门控是 `format` 族粒度——同族内删多条 `@@ OBJ:` pattern
  之一不触发报错。
判据缺的是「基线」，而**手写基线计数**正是本任务要消灭的东西（用户 2026-10-22：
「减少各种计数和比较」。）

做法：**生成式身份清单 + 幂等重生成比对**
------------------------------------------
本工具由**现场语料**（`tests/inst/**/*.yaml` 的用例、`tests/unit/llvm/lit/**/*.s`
的 `@@ OBJ:` pattern）重新派生一份**逐条身份清单**（不含任何计数），与入库的
`tests/case-ledger.tsv` 逐字节比对：
  * 删任一用例 / 任一 lit pattern ⇒ 清单少一行 ⇒ FAIL（定位到具体行）；
  * 增/改用例 ⇒ 重跑 `--write` 重新生成（生成物，非手写期望）。
身份 = 内容（id/class/word/fault/status 或 mnemonic/word）+ 同内容出现序号；
**不含行号**，故无关行插入/挪动不会产生噪声。

用法：
  python3 tools/infra/check_case_ledger.py            # 门控（默认）
  python3 tools/infra/check_case_ledger.py --write    # 重新生成清单
  python3 tools/infra/check_case_ledger.py --self-test
"""
from __future__ import annotations

import argparse
import collections
import glob
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

# libyaml 快档（纯 Python loader 在 1.4k 用例上 ~5s；L1 预算 <5s/项）。
_YAML_LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)

ROOT = Path(__file__).resolve().parents[2]
LEDGER_REL = "tests/case-ledger.tsv"
HEADER = (
    "# AUTO-GENERATED by tools/infra/check_case_ledger.py — DO NOT EDIT\n"
    "# 逐条身份清单（无计数）：删除任一 vector 用例 / lit @@ OBJ: pattern 即漂移。\n"
    "# 重新生成：python3 tools/infra/check_case_ledger.py --write\n"
    "# kind\tfile\tidentity...\tordinal\n"
)

LIT_OBJ_RE = re.compile(
    r"@@\s*OBJ:\s+\{\{\[0-9a-f\]\+:\}\}\s+"
    r"([0-9a-f]{2})\s+([0-9a-f]{2})\s+([0-9a-f]{2})\s+([0-9a-f]{2})"
    r"\{\{.*?\}\}([A-Za-z][A-Za-z0-9._]*)")


def _vector_rows(repo: Path) -> list[str]:
    rows = []
    for path in sorted(glob.glob(str(repo / "tests" / "inst" / "**" / "*.yaml"),
                                 recursive=True)):
        try:
            data = yaml.load(Path(path).read_text(encoding="utf-8"),
                             Loader=_YAML_LOADER)
        except (OSError, yaml.YAMLError):
            continue  # 非用例文件 / 损坏文件由其它门控负责
        if not isinstance(data, list):
            continue
        rel = Path(path).relative_to(repo).as_posix()
        seen: collections.Counter = collections.Counter()
        for case in data:
            if not isinstance(case, dict):
                continue
            enc = case.get("encoding") or {}
            word = str(enc.get("word", "")) if isinstance(enc, dict) else ""
            ident = (
                str(case.get("id", "")),
                str(case.get("class", "")),
                word.lower(),
                str(case.get("expected_fault", "")),
                str(case.get("status", "")),
            )
            seen[ident] += 1
            rows.append("vector\t%s\t%s\t%d" % (
                rel, "\t".join(ident), seen[ident]))
    return rows


def _lit_rows(repo: Path) -> list[str]:
    rows = []
    for path in sorted(glob.glob(str(repo / "tests" / "unit" / "llvm" / "lit" / "**" / "*.s"),
                                 recursive=True)):
        rel = Path(path).relative_to(repo).as_posix()
        seen: collections.Counter = collections.Counter()
        try:
            text = Path(path).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            m = LIT_OBJ_RE.search(line)
            if not m:
                continue
            word = "".join(m.groups()[:4]).lower()
            mnemonic = m.group(5)
            ident = (word, mnemonic)
            seen[ident] += 1
            rows.append("lit\t%s\t%s\t%d" % (rel, "\t".join(ident), seen[ident]))
    return rows


def derive_rows(repo: Path) -> list[str]:
    rows = _vector_rows(repo) + _lit_rows(repo)
    return sorted(rows)


def render(repo: Path) -> str:
    return HEADER + "\n".join(derive_rows(repo)) + "\n"


def run(repo: Path, ledger: Path) -> int:
    if not ledger.is_file():
        print(f"check-case-ledger: FAIL — 清单缺失: {ledger}"
              "（生成物必须入库；缺失 ⇒ 无法判断用例是否被删）", file=sys.stderr)
        return 1
    want = render(repo)
    got = ledger.read_text(encoding="utf-8")
    want_rows = want.splitlines()
    got_rows = got.splitlines()
    kinds = collections.Counter(r.split("\t", 1)[0] for r in want_rows
                                if not r.startswith("#"))
    print(f"check-case-ledger: 现场身份 {len(want_rows) - len(HEADER.splitlines())} 条"
          f"（vector {kinds.get('vector', 0)} / lit {kinds.get('lit', 0)}）")

    if got == want:
        print("check-case-ledger: PASS（清单 == 现场派生；逐条用例/pattern 受守护）")
        return 0

    want_set = collections.Counter(want_rows)
    got_set = collections.Counter(got_rows)
    missing = list((want_set - got_set).elements())
    extra = list((got_set - want_set).elements())
    for row in missing[:10]:
        print(f"[FAIL] 清单缺少（用例/pattern 被删?）: {row}", file=sys.stderr)
    for row in extra[:10]:
        print(f"[FAIL] 清单多出（未重新生成?）: {row}", file=sys.stderr)
    print(f"check-case-ledger: FAIL — 清单与现场不一致（缺 {len(missing)} 行 / "
          f"多 {len(extra)} 行）", file=sys.stderr)
    return 1


def self_test() -> int:
    tmp_root = Path(tempfile.gettempdir()) / "opencode" / "INFRA-102t"
    tmp_root.mkdir(parents=True, exist_ok=True)
    tmpdir = Path(tempfile.mkdtemp(prefix="case-ledger-", dir=tmp_root))
    try:
        vec = tmpdir / "tests" / "inst" / "base"
        lit = tmpdir / "tests" / "llvm" / "lit" / "MC" / "DADAO"
        vec.mkdir(parents=True)
        lit.mkdir(parents=True)
        (vec / "demo.yaml").write_text(
            yaml.safe_dump([
                {"id": "add.si_riii_rd", "class": "encoding",
                 "encoding": {"word": "0x10000000"}, "expected_fault": None,
                 "status": "active"},
                {"id": "add.si_riii_rd", "class": "legality",
                 "encoding": {"word": "0x10000000"}, "expected_fault": "ILLI",
                 "status": "active"},
                {"id": "add.si_riii_rd", "class": "legality",
                 "encoding": {"word": "0x10000001"}, "expected_fault": "ILLI",
                 "status": "active"},
            ], allow_unicode=True), encoding="utf-8")
        (lit / "demo.s").write_text(
            "@@ OBJ: {{[0-9a-f]+:}} 10 00 00 00{{.*}}add.si\n"
            "@@ OBJ: {{[0-9a-f]+:}} 10 00 00 01{{.*}}add.si\n", encoding="utf-8")

        ledger = tmpdir / LEDGER_REL
        ledger.parent.mkdir(parents=True, exist_ok=True)
        ledger.write_text(render(tmpdir), encoding="utf-8")

        def reset() -> None:
            (vec / "demo.yaml").write_text(
                yaml.safe_dump([
                    {"id": "add.si_riii_rd", "class": "encoding",
                     "encoding": {"word": "0x10000000"}, "expected_fault": None,
                     "status": "active"},
                    {"id": "add.si_riii_rd", "class": "legality",
                     "encoding": {"word": "0x10000000"}, "expected_fault": "ILLI",
                     "status": "active"},
                    {"id": "add.si_riii_rd", "class": "legality",
                     "encoding": {"word": "0x10000001"}, "expected_fault": "ILLI",
                     "status": "active"},
                ], allow_unicode=True), encoding="utf-8")
            (lit / "demo.s").write_text(
                "@@ OBJ: {{[0-9a-f]+:}} 10 00 00 00{{.*}}add.si\n"
                "@@ OBJ: {{[0-9a-f]+:}} 10 00 00 01{{.*}}add.si\n",
                encoding="utf-8")

        plans = [
            ("baseline", 0),
            ("delete-one-vector-case", 1),
            ("delete-one-lit-pattern", 1),
            ("ledger-missing", 1),
            ("delete-and-regenerate", 0),
        ]
        ok = True
        for i, (name, expect_rc) in enumerate(plans, 1):
            reset()
            ledger.write_text(render(tmpdir), encoding="utf-8")
            if name == "delete-one-vector-case":
                data = yaml.load((vec / "demo.yaml").read_text(),
                                 Loader=_YAML_LOADER)
                data.pop()
                (vec / "demo.yaml").write_text(yaml.safe_dump(data, allow_unicode=True))
            elif name == "delete-one-lit-pattern":
                lines = (lit / "demo.s").read_text().splitlines()
                (lit / "demo.s").write_text("\n".join(lines[:-1]) + "\n")
            elif name == "ledger-missing":
                ledger.unlink()
            elif name == "delete-and-regenerate":
                data = yaml.load((vec / "demo.yaml").read_text(),
                                 Loader=_YAML_LOADER)
                data.pop()
                (vec / "demo.yaml").write_text(yaml.safe_dump(data, allow_unicode=True))
                ledger.write_text(render(tmpdir), encoding="utf-8")
            rc = run(tmpdir, ledger)
            good = rc == expect_rc
            print(f"[{'PASS' if good else 'FAIL'}] self-test case{i} {name}: "
                  f"期望 rc={expect_rc} 实际 rc={rc}")
            ok = ok and good
        return 0 if ok else 1
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", default=str(ROOT))
    ap.add_argument("--ledger", default=None)
    ap.add_argument("--write", action="store_true", help="重新生成清单")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    repo = Path(args.repo_root).resolve()
    ledger = Path(args.ledger) if args.ledger else repo / LEDGER_REL
    if args.self_test:
        rc = self_test()
        print(f"self-test: {'PASS' if rc == 0 else 'FAIL'}")
        return rc
    if args.write:
        ledger.write_text(render(repo), encoding="utf-8")
        print(f"check-case-ledger: wrote {ledger}")
        return 0
    return run(repo, ledger)


if __name__ == "__main__":
    raise SystemExit(main())
