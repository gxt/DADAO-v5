#!/usr/bin/env python3
"""Build picolibc for the DADAO-v5 ``dadao-unknown-elf`` target and install it.

This is the build half of the picolibc port (INFRA-057t).  It drives the
upstream Meson build with the DADAO cross file
(``scripts/cross-dadao.txt``, part of the component patch set) and installs the
result into the target sysroot (``target_sysroot_dir()``: headers under
``include/``, libraries under ``lib/``).

Idempotent: re-running reconfigures the same build tree and rebuilds only what
changed; the install step refreshes the sysroot.

A **toolchain stamp** guards the trees against stale objects (ISS-248): Meson
records the compiler path in ``coredata.dat`` but never notices that the binary
behind that path was replaced, so after ``make install-host`` an unchanged
``ninja`` says "no work to do" and the sysroot is refreshed with objects built
by the *old* backend.  The stamp records, for the three binaries that decide the
object code and the link result (``clang``, ``clang++``, ``ld.lld``), their
resolved path, size, mtime, ctime and ``--version`` line in
``.work/build/picolibc/.dadao-toolchain-stamp``; a mismatch -- or a missing
stamp -- wipes the build tree and reconfigures from scratch, and the decision is
always logged.  A preserved-mtime reinstall still lands as a new ctime (and
usually a new inode), so that case is covered too.

Port scope (INFRA-057t, minimized by INFRA-066t): the DADAO LLVM backend still
cannot lower some DAG nodes / libcalls that a few sources need; those sources
(the *minimal* set of 41, derived in INFRA-066t by compiling every source in
this build) are listed in the component's ``meson.build``.  The full math library
now builds into ``libc.a`` (picolibc merges libc+libm into one archive and ships
an empty ``libm.a`` for ``-lm`` compatibility); see ``ISS-193`` for the residual
gaps.

Tools: ``clang``/``clang++``/``ld.lld`` come from the install root's
cross-toolchain ``bin/`` (put on PATH here); ``ar``/``nm``/``strip`` are the
host binutils.  ``meson`` and ``ninja`` must be on PATH.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths  # noqa: E402

REPO_ROOT = paths.repo_root()
TOOLCHAIN_BIN = paths.host_toolchain_bin()
WORK_ROOT = REPO_ROOT / ".work"
SOURCE = WORK_ROOT / "source" / "picolibc"
BUILD = WORK_ROOT / "build" / "picolibc"
CROSS_FILE = SOURCE / "scripts" / "cross-dadao.txt"
SYSROOT = paths.target_sysroot_dir()

# ── toolchain staleness guard (ISS-248) ─────────────────────────────────────
# See the module docstring.  The stamp lives inside the Meson build tree, which
# is regenerated by the wipe that a stamp change triggers; `.work/` is outside
# the git tree, so check-no-residue/check-source-state are unaffected.
STAMP_TOOLS = ("clang", "clang++", "ld.lld")
STAMP_REL = Path(".dadao-toolchain-stamp")

MESON_ARGS = [
    "-Dmultilib=false",
    "-Dtests=false",
    "-Dpicocrt=true",
    "-Ddebug=false",
    # DADAO port scope: the backend cannot select the ryu float/string
    # conversion code, so select the smaller engine-based conversions.
    # `io-float-exact=false` builds dtoa_engine.c / atod_engine.c /
    # atof_engine.c, which define `__dtoa_engine` / `__atod_engine` (referenced
    # by vfprintf and conv_flt); the upstream default `true` builds the ryu
    # variant and leaves `__dtoa_engine` undefined on this target.  This is
    # passed on the command line rather than via the cross file's
    # `[project options]` because Meson re-applies CLI options on
    # `--reconfigure` but does not re-read cross-file project-option defaults
    # (the idempotent rebuild path uses `--reconfigure`).
    "-Dio-float-exact=false",
    f"-Dprefix={SYSROOT}",
    "-Dincludedir=include",
    "-Dlibdir=lib",
]


def run(cmd: list[str], *, env: dict[str, str], cwd: Path | None = None) -> None:
    print("build-picolibc:", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, env=env, cwd=cwd)


def need_tool(name: str, *, what: str) -> None:
    if shutil.which(name) is None:
        sys.exit(f"build-picolibc: ERROR: {name!r} not found on PATH ({what})")


def toolchain_stamp() -> str:
    """One line per code-deciding toolchain binary: what the objects were built by."""
    lines = []
    for tool in STAMP_TOOLS:
        path = TOOLCHAIN_BIN / tool
        real = path.resolve()
        st = real.stat()
        res = subprocess.run([str(path), "--version"], stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT, text=True)
        version = ((res.stdout.splitlines() or [""])[0] if res.returncode == 0
                   else f"rc={res.returncode}")
        lines.append(f"{tool} -> {real} size={st.st_size} "
                     f"mtime={st.st_mtime_ns} ctime={st.st_ctime_ns} {version}")
    return "\n".join(lines) + "\n"


def read_stamp() -> str | None:
    try:
        return (BUILD / STAMP_REL).read_text()
    except OSError:
        return None


def write_stamp(text: str) -> None:
    path = BUILD / STAMP_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def stamp_decision() -> tuple[bool, str, str]:
    """(changed, reason, current stamp) for the build tree at BUILD.

    ``changed`` means the objects present in the tree were produced by a
    different toolchain (or by an unknown one) and must not be reused.
    """
    current = toolchain_stamp()
    stored = read_stamp()
    if stored is None:
        return True, "no toolchain stamp recorded for this build tree", current
    if stored.strip() == current.strip():
        return False, "toolchain stamp unchanged (objects are up to date)", current
    return True, "toolchain stamp changed", current


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--jobs", type=int, default=int(os.environ.get("JOBS", "8")))
    args = ap.parse_args()

    if not SOURCE.is_dir():
        sys.exit(f"build-picolibc: ERROR: {SOURCE} missing — run 'make fetch' first")
    if not CROSS_FILE.is_file():
        sys.exit(
            f"build-picolibc: ERROR: {CROSS_FILE} missing — apply the picolibc patch "
            "series first ('make apply-series')"
        )
    toolchain_bin = TOOLCHAIN_BIN
    for tool in STAMP_TOOLS:
        if not (toolchain_bin / tool).exists():
            sys.exit(
                f"build-picolibc: ERROR: {toolchain_bin / tool} not found — "
                "run 'make install-host' first"
            )

    need_tool("meson", what="host build tool")
    need_tool("ninja", what="host build tool")
    need_tool("ar", what="host binutils")

    env = dict(os.environ)
    env["PATH"] = str(toolchain_bin) + os.pathsep + env.get("PATH", "")

    SYSROOT.mkdir(parents=True, exist_ok=True)

    try:
        changed, reason, current = stamp_decision()
    except OSError as exc:
        sys.exit(f"build-picolibc: ERROR: cannot stamp the toolchain ({exc})")
    if changed:
        print(f"build-picolibc: {reason} => wiping {BUILD} (full rebuild)", flush=True)
        print("build-picolibc: current toolchain stamp:\n" + current.rstrip(), flush=True)
        try:
            shutil.rmtree(BUILD)
        except FileNotFoundError:
            pass
        except OSError as exc:
            # Fail closed: a wipe that did not happen would put the stale objects
            # straight back into the "incremental" path.
            sys.exit(f"build-picolibc: ERROR: cannot remove {BUILD} ({exc})")
        # Record before building: the tree has just been removed, so whatever
        # Meson/ninja produce from here on *is* built by this toolchain -- a
        # failed build then resumes incrementally instead of paying another wipe.
        write_stamp(current)
    else:
        print(f"build-picolibc: {reason} => incremental build", flush=True)

    configured = (BUILD / "meson-private" / "coredata.dat").is_file()
    setup = ["meson", "setup"]
    if configured:
        setup.append("--reconfigure")
    setup += [str(BUILD), str(SOURCE), "--cross-file", str(CROSS_FILE), *MESON_ARGS]
    run(setup, env=env)

    run(["ninja", f"-j{args.jobs}", "-C", str(BUILD)], env=env)
    run(["meson", "install", "-C", str(BUILD), "--no-rebuild"], env=env)

    libc = SYSROOT / "lib" / "libc.a"
    semihost = SYSROOT / "lib" / "libsemihost.a"
    if not libc.is_file():
        sys.exit(f"build-picolibc: ERROR: {libc} was not installed")
    print(
        f"build-picolibc: PASS — {libc} ({libc.stat().st_size} bytes), "
        f"{semihost} ({semihost.stat().st_size} bytes), "
        f"headers under {SYSROOT / 'include'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
