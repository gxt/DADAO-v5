#!/usr/bin/env python3
"""Generate an independent full-field DADAO decoder oracle table."""

from __future__ import annotations

import argparse
import collections
from dataclasses import dataclass
from pathlib import Path

import yaml

from check_dadao_static_legality import expected_checks


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OPS = ROOT / "contracts/opcodes.yaml"
DEFAULT_OUTPUT = (
    ROOT
    / "rtl/dadao/src/test/scala/dadao/"
    / "DADAODecoderOracleTable.scala"
)

SCOPE_CODES = {
    "m1": 0,
    "fp": 1,
    "excluded": 2,
    "m3": 3,
    "m8": 3,
    "m9": 3,
}

FAULT_NONE = 0x00
FAULT_ILLI = 0x88

REASON_NONE = 0
REASON_ILLI_OPERAND = 1
REASON_ILLI_FIELD = 2
REASON_ILLI_SCOPE_FP = 3
REASON_ILLI_SCOPE_EXCLUDED = 4
REASON_ILLI_SCOPE_M3 = 5

OPERAND_KINDS = {1, 2, 3, 4, 5, 6}


@dataclass(frozen=True)
class OracleEntry:
    word: int
    ident: int
    format_code: int
    scope: int
    slot0: int
    slot1: int
    slot2: int
    slot3: int
    imm12: int
    imm18: int
    imm24: int
    is_noop: int
    fault: int
    fault_code: int
    debug_reason: int
    unsupported: int


def parse_int(value: object, field: str, record_id: str) -> int:
    if not isinstance(value, str):
        raise AssertionError(f"{record_id}: {field} is not a string")
    return int(value, 0)


def field_value(word: int, offset: int, width: int = 6) -> int:
    return (word >> offset) & ((1 << width) - 1)


def check_illegal(
    word: int,
    check: tuple[int, int, int, int, int],
) -> bool:
    kind, field_a, field_b, field_c, limit = check
    a = field_value(word, field_a)
    b = field_value(word, field_b)
    c = field_value(word, field_c)

    if kind == 1:
        return a == 0
    if kind == 2:
        return (a == 0 and b == 0) or (a == b and a != 0)
    if kind == 3:
        return a == 0 and (word & ((1 << 18) - 1)) != 0
    if kind == 4:
        return a == 0
    if kind == 5:
        return a + b > 64
    if kind == 6:
        return a < b + c and b < a + c
    if kind == 7:
        return a > limit
    if kind == 8:
        return a != limit
    if kind == 9:
        return (word & limit) != 0
    if kind == 10:
        return (6 <= a <= 14) or (19 <= a <= 61)
    raise AssertionError(f"unsupported static check kind {kind}")


def expected_state(record: dict, ident: int) -> OracleEntry:
    record_id = str(record["id"])
    word = parse_int(record["value"], "value", record_id)
    scope_name = str(record["scope"])
    scope = SCOPE_CODES[scope_name]

    operand_fault = False
    field_fault = False
    if scope_name == "m1":
        for check in expected_checks(record):
            if not check_illegal(word, check):
                continue
            if check[0] in OPERAND_KINDS:
                operand_fault = True
            else:
                field_fault = True

    if scope_name != "m1":
        fault = 1
        fault_code = FAULT_ILLI
        reason = {
            "fp": REASON_ILLI_SCOPE_FP,
            "excluded": REASON_ILLI_SCOPE_EXCLUDED,
            "m3": REASON_ILLI_SCOPE_M3,
            "m8": REASON_ILLI_SCOPE_M3,
            "m9": REASON_ILLI_SCOPE_M3,
        }[scope_name]
    elif operand_fault:
        fault = 1
        fault_code = FAULT_ILLI
        reason = REASON_ILLI_OPERAND
    elif field_fault:
        fault = 1
        fault_code = FAULT_ILLI
        reason = REASON_ILLI_FIELD
    else:
        fault = 0
        fault_code = FAULT_NONE
        reason = REASON_NONE

    return OracleEntry(
        word=word,
        ident=ident,
        format_code=0,
        scope=scope,
        slot0=field_value(word, 18),
        slot1=field_value(word, 12),
        slot2=field_value(word, 6),
        slot3=field_value(word, 0),
        imm12=word & 0xFFF,
        imm18=word & 0x3FFFF,
        imm24=word & 0xFFFFFF,
        is_noop=int(str(record["mnemonic"]) == "swym"),
        fault=fault,
        fault_code=fault_code,
        debug_reason=reason,
        unsupported=int(scope_name != "m1"),
    )


def build_oracle(records: list[dict]) -> tuple[
    list[OracleEntry],
    list[str],
]:
    formats = sorted({str(record["format"]) for record in records})
    format_codes = {name: index for index, name in enumerate(formats)}
    rows = []
    for ident, record in enumerate(records):
        base = expected_state(record, ident)
        rows.append(
            OracleEntry(
                **{
                    **base.__dict__,
                    "format_code": format_codes[str(record["format"])],
                }
            )
        )
    return rows, formats


def emit_scala(
    path: Path,
    rows: list[OracleEntry],
    formats: list[str],
) -> None:
    lines = [
        "package dadao",
        "",
        "// Generated by tools/rtl/check_dadao_decoder_oracle.py.",
        "// Expected from contracts/opcodes.yaml, independent of RTL.",
        "private[dadao] final case class DADAODecoderOracleEntry(",
        "    word: BigInt,",
        "    id: Int,",
        "    format: Int,",
        "    scope: Int,",
        "    slot0: Int,",
        "    slot1: Int,",
        "    slot2: Int,",
        "    slot3: Int,",
        "    imm12: Int,",
        "    imm18: Int,",
        "    imm24: Int,",
        "    isNoop: Boolean,",
        "    fault: Boolean,",
        "    faultCode: Int,",
        "    debugReason: Int,",
        "    unsupported: Boolean",
        ")",
        "",
        "private[dadao] object DADAODecoderOracleTable {",
        "  val entries: Seq[DADAODecoderOracleEntry] = Seq(",
    ]
    for row in rows:
        lines.append(
            "    DADAODecoderOracleEntry("
            f'BigInt("{row.word:08x}", 16), '
            f"{row.ident}, {row.format_code}, {row.scope}, "
            f"{row.slot0}, {row.slot1}, {row.slot2}, {row.slot3}, "
            f"{row.imm12}, {row.imm18}, {row.imm24}, "
            f"{str(bool(row.is_noop)).lower()}, "
            f"{str(bool(row.fault)).lower()}, {row.fault_code}, "
            f"{row.debug_reason}, "
            f"{str(bool(row.unsupported)).lower()}),"
        )
    lines.extend(
        [
            "  )",
            "  val formatNames: Seq[String] = Seq(",
            *[f'    "{name}",' for name in formats],
            "  )",
            "}",
            "",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate full-field DADAO decoder oracle."
    )
    parser.add_argument("--ops", type=Path, default=DEFAULT_OPS)
    parser.add_argument("--emit-scala", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--force-failure", action="store_true")
    args = parser.parse_args()

    records = yaml.safe_load(args.ops.read_text(encoding="utf-8"))
    if not isinstance(records, list):
        raise AssertionError("opcodes.yaml must contain a list")

    rows, formats = build_oracle(records)
    scope_counts = collections.Counter(str(record["scope"]) for record in records)
    if len(rows) != 264 or len(formats) != 11:
        raise AssertionError(
            f"unexpected oracle dimensions: rows={len(rows)}, "
            f"formats={len(formats)}"
        )
    if scope_counts != {
        "m1": 156,
        "fp": 66,
        "m3": 1,
        "m8": 7,
        "m9": 34,
    }:
        raise AssertionError(f"unexpected scope counts: {scope_counts}")

    emit_scala(args.emit_scala, rows, formats)
    print(f"oracle_entries={len(rows)}")
    print(f"formats={len(formats)}")
    print(
        f"m1={scope_counts['m1']} fp={scope_counts['fp']} "
        f"excluded={scope_counts['excluded']} m3={scope_counts['m3']} "
        f"m8={scope_counts['m8']} m9={scope_counts['m9']}"
    )
    print(f"emitted={args.emit_scala}")

    if args.force_failure:
        raise AssertionError("forced decoder-oracle failure")

    print("DECODER_ORACLE CHECK PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
