#!/usr/bin/env python3
"""make_defconfig.py — configure the DADAO kernel (`make linux-defconfig`).

K0 scope (`m14-linux-002`): the kernel only has to configure and link.  The
default configuration is `arch/dadao/configs/defconfig`: one hart, no SMP, no
device tree, 64 KiB pages, big endian, semihosting console stub.

Everything runtime (source tree, build tree, install root) comes from
`tools/linux/paths.py`; nothing here hardcodes a host path.

Toolchain note (live): the installed `clang` driver has no default target
triple (`clang -dumpmachine` -> `unknown`), so `scripts/cc-version.sh` cannot
classify it and Kbuild stops with "unknown C compiler".  A two-line wrapper
that appends `--target=dadao-unknown-elf` is written into the *build* tree
(disposable runtime artefact) and passed as `CC`; `CLANG_TARGET_FLAGS` is
passed on the make command line for the same reason (`scripts/Makefile.clang`
only knows the upstream architecture list, which we do not patch).

Usage:
  python3 tools/linux/make_defconfig.py [--jobs N]

Exit status: 0 = configured; 1 = make failed; 2 = setup error (missing tree,
tool or applied patch series).
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.linux import paths as linux_paths  # noqa: E402

TARGET = "dadao-unknown-elf"
ARCH = "dadao"
#: Guards the LDFLAGS below when `make` is called with command-line
#: assignments (they win over the arch Makefile).
LDFLAGS_VMLINUX = "-z max-page-size=0x10000 -z common-page-size=0x10000 --no-rosegment"


class SetupError(Exception):
    """Prerequisite missing: the caller must fix the environment first."""


def default_jobs() -> int:
    jobs = os.environ.get("JOBS")
    if jobs and jobs.isdigit() and int(jobs) > 0:
        return int(jobs)
    return max(1, (os.cpu_count() or 2) // 2)


def _require_executable(name: str, path: Path, hint: str) -> str:
    if not path.is_file() or not os.access(path, os.X_OK):
        raise SetupError(f"{name} not found at {path}; run `{hint}` first")
    return str(path)


def write_cc_wrapper(build_dir: Path, clang: Path) -> Path:
    """Create the `clang --target=dadao-unknown-elf` driver wrapper."""
    tools_dir = build_dir / "tools"
    tools_dir.mkdir(parents=True, exist_ok=True)
    wrapper = tools_dir / "clang-dadao"
    body = (
        "#!/bin/sh\n"
        "# Generated by tools/linux/make_defconfig.py (runtime artefact).\n"
        f'exec "{clang}" --target={TARGET} "$@"\n'
    )
    if not wrapper.is_file() or wrapper.read_text(encoding="utf-8") != body:
        wrapper.write_text(body, encoding="utf-8")
    wrapper.chmod(0o755)
    return wrapper


def tool_vars() -> dict[str, str]:
    """CC/LD/AR/... for the kernel build.

    `llvm-ar`/`llvm-ranlib`/`llvm-strip` are present in the install root
    (m14-llvm-001 backfill).  `tools/linux/toolchain_matrix.json` keeps the
    documented fallback for an install root without them; the fallback is used
    only when the tool is really absent, never silently.
    """
    bin_dir = linux_paths.toolchain_bin()
    if not bin_dir.is_dir():
        raise SetupError(
            f"toolchain bin/ not found at {bin_dir}; run `make install-host` first"
        )

    clang = bin_dir / "clang"
    ld = bin_dir / "ld.lld"
    nm = bin_dir / "llvm-nm"
    objcopy = bin_dir / "llvm-objcopy"
    objdump = bin_dir / "llvm-objdump"
    readelf = bin_dir / "llvm-readelf"
    cc = _require_executable("clang", clang, "make install-host")
    ld = _require_executable("ld.lld", ld, "make install-host")
    objcopy = _require_executable("llvm-objcopy", objcopy, "make install-host")
    objdump = _require_executable("llvm-objdump", objdump, "make install-host")
    readelf = _require_executable("llvm-readelf", readelf, "make install-host")

    if not nm.is_file():
        raise SetupError(
            f"llvm-nm not found at {nm}; run `make install-host` first"
        )

    src = linux_paths.linux_source_dir()
    build = linux_paths.linux_build_dir()
    build.mkdir(parents=True, exist_ok=True)
    wrapper = write_cc_wrapper(build, clang)

    ar = bin_dir / "llvm-ar"
    ranlib = bin_dir / "llvm-ranlib"
    strip = bin_dir / "llvm-strip"
    if not ar.is_file():
        # Documented workaround (toolchain_matrix.json): the archive format is
        # target independent and GNU ar was verified on DADAO objects.
        ar = Path(shutil.which("ar") or "")
        if not ar.is_file():
            raise SetupError("neither llvm-ar nor GNU ar is available")
    if not ranlib.is_file():
        ranlib = Path(shutil.which("ranlib") or "")
        if not ranlib.is_file():
            raise SetupError("neither llvm-ranlib nor GNU ranlib is available")
    if not strip.is_file():
        # GNU strip cannot read an EM_DADAO big-endian ELF; llvm-objcopy is
        # the documented substitute.  It is not invoked by `vmlinux`.
        strip = bin_dir / "llvm-objcopy"

    return {
        "CC": str(wrapper),
        "LD": ld,
        "AR": str(ar),
        "NM": str(nm),
        "RANLIB": str(ranlib),
        "OBJCOPY": objcopy,
        "OBJDUMP": objdump,
        "READELF": readelf,
        "STRIP": str(strip),
        "CLANG_TARGET_FLAGS": TARGET,
        "ARCH": ARCH,
    }


def kernel_make_base() -> tuple[list[str], dict[str, str]]:
    """Command prefix + environment shared by the configure/build scripts."""
    src = linux_paths.linux_source_dir()
    if not src.is_dir():
        raise SetupError(f"kernel source tree missing at {src}; run `make fetch`")
    if not (src / "arch" / ARCH).is_dir():
        raise SetupError(
            f"arch/{ARCH} is not present in the source tree at {src}; "
            "run `make fetch apply-series`"
        )
    build = linux_paths.linux_build_dir()
    build.mkdir(parents=True, exist_ok=True)

    variables = tool_vars()
    cmd = [
        "make",
        "-C",
        str(src),
        f"O={build}",
    ]
    cmd += [f"{key}={value}" for key, value in variables.items()]
    return cmd, variables


def next_step_hint() -> None:
    print(
        "make_defconfig: next steps: `make install-host` (toolchain), "
        "`make fetch apply-series` (source tree)",
        file=sys.stderr,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=default_jobs(),
                        help="parallel make jobs (default: JOBS or nproc/2)")
    args = parser.parse_args()

    try:
        cmd, _ = kernel_make_base()
    except SetupError as exc:
        print(f"make_defconfig: SETUP ERROR: {exc}", file=sys.stderr)
        return 2

    cmd.append("defconfig")
    print(f"[INFO] {' '.join(cmd)}", flush=True)
    try:
        rc = subprocess.call(cmd)
    except OSError as exc:
        print(f"make_defconfig: SETUP ERROR: cannot exec make: {exc}",
              file=sys.stderr)
        return 2
    if rc != 0:
        print(f"make_defconfig: FAIL: `make defconfig` exited {rc}",
              file=sys.stderr)
        next_step_hint()
        return 1

    config = linux_paths.linux_build_dir() / ".config"
    if not config.is_file():
        print(f"make_defconfig: FAIL: {config.name} was not written",
              file=sys.stderr)
        return 1
    print("make_defconfig: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
