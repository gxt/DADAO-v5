#!/usr/bin/env python3
"""make_defconfig.py — configure the DADAO kernel (`make linux-defconfig`).

K0 scope (`m14-linux-002`): the kernel only has to configure and link.  The
default configuration is `arch/dadao/configs/defconfig`: one hart, no SMP, no
device tree, 64 KiB pages, big endian, semihosting console stub.

Everything runtime (source tree, build tree, install root) comes from
`tools/linux/paths.py`; nothing here hardcodes a host path.

Toolchain note (live): the installed `clang` driver has no default target
triple (`clang -dumpmachine` -> `unknown`), so `scripts/cc-version.sh` cannot
classify it and Kbuild stops with "unknown C compiler".  A two-line wrapper
that appends `--target=dadao-unknown-elf` is written into the *build* tree
(disposable runtime artefact) and passed as `CC`; `CLANG_TARGET_FLAGS` is
passed on the make command line for the same reason (`scripts/Makefile.clang`
only knows the upstream architecture list, which we do not patch).

Configuration slices (`--extra-config`, m14-linux-006): the default
configuration is `arch/dadao/configs/defconfig` — the *K2* image (no
`CONFIG_DADAO_K1_EARLY_STOP`).  An image that needs a symbol the default does
not set states it explicitly, e.g. the K1 gate rebuilds with

  --extra-config CONFIG_DADAO_K1_EARLY_STOP=y

`apply_config_lines()` is the same entry point for scripts: it lands the lines
in the build tree's `.config` and re-runs `olddefconfig` so dependencies
converge.  Every gate therefore sets up the configuration its image needs
instead of inheriting whatever the previous command left behind.

Usage:
  python3 tools/linux/make_defconfig.py [--jobs N] [--extra-config SYM=VAL ...]

Exit status: 0 = configured; 1 = make failed; 2 = setup error (missing tree,
tool or applied patch series).
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.linux import paths as linux_paths  # noqa: E402

TARGET = "dadao-unknown-elf"
ARCH = "dadao"
#: Guards the LDFLAGS below when `make` is called with command-line
#: assignments (they win over the arch Makefile).
LDFLAGS_VMLINUX = "-z max-page-size=0x10000 -z common-page-size=0x10000 --no-rosegment"


class SetupError(Exception):
    """Prerequisite missing: the caller must fix the environment first."""


def default_jobs() -> int:
    jobs = os.environ.get("JOBS")
    if jobs and jobs.isdigit() and int(jobs) > 0:
        return int(jobs)
    return max(1, (os.cpu_count() or 2) // 2)


def _require_executable(name: str, path: Path, hint: str) -> str:
    if not path.is_file() or not os.access(path, os.X_OK):
        raise SetupError(f"{name} not found at {path}; run `{hint}` first")
    return str(path)


def write_cc_wrapper(build_dir: Path, clang: Path) -> Path:
    """Create the `clang --target=dadao-unknown-elf` driver wrapper."""
    tools_dir = build_dir / "tools"
    tools_dir.mkdir(parents=True, exist_ok=True)
    wrapper = tools_dir / "clang-dadao"
    body = (
        "#!/bin/sh\n"
        "# Generated by tools/linux/make_defconfig.py (runtime artefact).\n"
        f'exec "{clang}" --target={TARGET} "$@"\n'
    )
    if not wrapper.is_file() or wrapper.read_text(encoding="utf-8") != body:
        wrapper.write_text(body, encoding="utf-8")
    wrapper.chmod(0o755)
    return wrapper


def tool_vars() -> dict[str, str]:
    """CC/LD/AR/... for the kernel build.

    `llvm-ar`/`llvm-ranlib`/`llvm-strip` are present in the install root
    (m14-llvm-001 backfill).  `tools/linux/toolchain_matrix.json` keeps the
    documented fallback for an install root without them; the fallback is used
    only when the tool is really absent, never silently.
    """
    bin_dir = linux_paths.toolchain_bin()
    if not bin_dir.is_dir():
        raise SetupError(
            f"toolchain bin/ not found at {bin_dir}; run `make install-host` first"
        )

    clang = bin_dir / "clang"
    ld = bin_dir / "ld.lld"
    nm = bin_dir / "llvm-nm"
    objcopy = bin_dir / "llvm-objcopy"
    objdump = bin_dir / "llvm-objdump"
    readelf = bin_dir / "llvm-readelf"
    cc = _require_executable("clang", clang, "make install-host")
    ld = _require_executable("ld.lld", ld, "make install-host")
    objcopy = _require_executable("llvm-objcopy", objcopy, "make install-host")
    objdump = _require_executable("llvm-objdump", objdump, "make install-host")
    readelf = _require_executable("llvm-readelf", readelf, "make install-host")

    if not nm.is_file():
        raise SetupError(
            f"llvm-nm not found at {nm}; run `make install-host` first"
        )

    src = linux_paths.linux_source_dir()
    build = linux_paths.linux_build_dir()
    build.mkdir(parents=True, exist_ok=True)
    wrapper = write_cc_wrapper(build, clang)

    ar = bin_dir / "llvm-ar"
    ranlib = bin_dir / "llvm-ranlib"
    strip = bin_dir / "llvm-strip"
    if not ar.is_file():
        # Documented workaround (toolchain_matrix.json): the archive format is
        # target independent and GNU ar was verified on DADAO objects.
        ar = Path(shutil.which("ar") or "")
        if not ar.is_file():
            raise SetupError("neither llvm-ar nor GNU ar is available")
    if not ranlib.is_file():
        ranlib = Path(shutil.which("ranlib") or "")
        if not ranlib.is_file():
            raise SetupError("neither llvm-ranlib nor GNU ranlib is available")
    if not strip.is_file():
        # GNU strip cannot read an EM_DADAO big-endian ELF; llvm-objcopy is
        # the documented substitute.  It is not invoked by `vmlinux`.
        strip = bin_dir / "llvm-objcopy"

    return {
        "CC": str(wrapper),
        "LD": ld,
        "AR": str(ar),
        "NM": str(nm),
        "RANLIB": str(ranlib),
        "OBJCOPY": objcopy,
        "OBJDUMP": objdump,
        "READELF": readelf,
        "STRIP": str(strip),
        "CLANG_TARGET_FLAGS": TARGET,
        "ARCH": ARCH,
    }


def kernel_make_base() -> tuple[list[str], dict[str, str]]:
    """Command prefix + environment shared by the configure/build scripts."""
    src = linux_paths.linux_source_dir()
    if not src.is_dir():
        raise SetupError(f"kernel source tree missing at {src}; run `make fetch`")
    if not (src / "arch" / ARCH).is_dir():
        raise SetupError(
            f"arch/{ARCH} is not present in the source tree at {src}; "
            "run `make fetch apply-series`"
        )
    build = linux_paths.linux_build_dir()
    build.mkdir(parents=True, exist_ok=True)

    variables = tool_vars()
    cmd = [
        "make",
        "-C",
        str(src),
        f"O={build}",
    ]
    cmd += [f"{key}={value}" for key, value in variables.items()]
    return cmd, variables


def next_step_hint() -> None:
    print(
        "make_defconfig: next steps: `make install-host` (toolchain), "
        "`make fetch apply-series` (source tree)",
        file=sys.stderr,
    )


def config_path() -> Path:
    """The build tree's `.config` (runtime artefact, never in the component)."""
    return linux_paths.linux_build_dir() / ".config"


def _parse_entry(entry: str) -> tuple[str, str]:
    """Split `CONFIG_X=value`; reject anything Kconfig would not accept."""
    symbol, sep, value = entry.partition("=")
    symbol, value = symbol.strip(), value.strip()
    if not sep or not symbol.startswith("CONFIG_") or not value:
        raise SetupError(f"--extra-config expects CONFIG_SYM=VALUE, got {entry!r}")
    return symbol, value


def _config_line(symbol: str, value: str) -> str:
    """The line Kconfig writes for @symbol = @value (`n` is a comment)."""
    return f"# {symbol} is not set" if value == "n" else f"{symbol}={value}"


def apply_config_lines(entries: list[str]) -> int:
    """Land explicit config values in the build tree's `.config`, then converge.

    @entries may be empty (the existing `.config` stands).  The requested values
    are asserted *after* `olddefconfig`: a symbol the dependency graph drops
    silently would otherwise produce a different image than the caller asked
    for.

    Exit status: 0 = `.config` carries every requested value; 1 =
    `olddefconfig` failed or a value did not survive; 2 = setup error.
    """
    if not entries:
        return 0
    try:
        requested = [_parse_entry(entry) for entry in entries]
    except SetupError as exc:
        print(f"make_defconfig: SETUP ERROR: {exc}", file=sys.stderr)
        return 2

    config = config_path()
    if not config.is_file():
        print(f"make_defconfig: SETUP ERROR: {config} is missing; "
              f"run `make linux-defconfig` first", file=sys.stderr)
        return 2

    lines = config.read_text(encoding="utf-8").splitlines()
    for symbol, value in requested:
        lines = [line for line in lines
                 if not line.startswith(f"{symbol}=")
                 and line != f"# {symbol} is not set"]
        lines.append(_config_line(symbol, value))
    config.write_text("\n".join(lines) + "\n", encoding="utf-8")

    try:
        cmd, _variables = kernel_make_base()
    except SetupError as exc:
        print(f"make_defconfig: SETUP ERROR: {exc}", file=sys.stderr)
        return 2
    rc = subprocess.call(cmd + ["olddefconfig"])
    if rc != 0:
        print(f"make_defconfig: FAIL: `make olddefconfig` exited {rc}",
              file=sys.stderr)
        return 1

    text = config.read_text(encoding="utf-8").splitlines()
    for symbol, value in requested:
        if value == "n":
            # Kconfig writes `# CONFIG_X is not set`, or omits the symbol
            # entirely when its dependencies are unmet; both mean "not set".
            survivors = [line for line in text if line.startswith(f"{symbol}=")]
            if survivors:
                print(f"make_defconfig: FAIL: {symbol} should be unset but "
                      f"reads {survivors[0]!r}", file=sys.stderr)
                return 1
        elif _config_line(symbol, value) not in text:
            print(f"make_defconfig: FAIL: {symbol}={value} did not survive "
                  f"`olddefconfig`", file=sys.stderr)
            return 1
    print("make_defconfig: config slice applied: "
          + " ".join(_config_line(s, v) for s, v in requested))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=default_jobs(),
                        help="parallel make jobs (default: JOBS or nproc/2)")
    parser.add_argument("--extra-config", action="append", default=[],
                        metavar="CONFIG_SYM=VALUE",
                        help="config slice applied after `make defconfig` "
                             "(repeatable); `=n` writes Kconfig's "
                             "`# CONFIG_SYM is not set`")
    args = parser.parse_args()

    try:
        cmd, _ = kernel_make_base()
    except SetupError as exc:
        print(f"make_defconfig: SETUP ERROR: {exc}", file=sys.stderr)
        return 2

    cmd.append("defconfig")
    print(f"[INFO] {' '.join(cmd)}", flush=True)
    try:
        rc = subprocess.call(cmd)
    except OSError as exc:
        print(f"make_defconfig: SETUP ERROR: cannot exec make: {exc}",
              file=sys.stderr)
        return 2
    if rc != 0:
        print(f"make_defconfig: FAIL: `make defconfig` exited {rc}",
              file=sys.stderr)
        next_step_hint()
        return 1

    config = config_path()
    if not config.is_file():
        print(f"make_defconfig: FAIL: {config.name} was not written",
              file=sys.stderr)
        return 1

    # The built-in initramfs (CONFIG_BLK_DEV_INITRD, set by the arch defconfig)
    # takes its contents from CONFIG_INITRAMFS_SOURCE.  The staging directory is
    # a *runtime* path resolved by tools/linux/paths.py, so it is written here
    # rather than in the component's defconfig; Kbuild assembles a cpio from the
    # directory itself, so the kernel and `make linux-initramfs` share one
    # definition of what `/init` and friends are.
    initramfs_cpio = linux_paths.linux_initramfs_dir() / "initramfs.cpio"
    initramfs_line = []
    if initramfs_cpio.is_file():
        # The *cpio* is the archive `make linux-initramfs` built (it carries
        # `bin/busybox` and the applet links); the directory around it only has
        # `/init`, `/init.musl` and the build artefacts, so pointing Kbuild at
        # the directory would silently ship a rootfs without a shell.
        initramfs_line = [f'CONFIG_INITRAMFS_SOURCE="{initramfs_cpio}"']
    rc = apply_config_lines(initramfs_line + list(args.extra_config))
    if rc != 0:
        print("make_defconfig: FAIL: the config slice did not apply",
              file=sys.stderr)
        return rc
    if not initramfs_line:
        print("make_defconfig: WARN: no initramfs archive "
              f"({initramfs_cpio}); the image will have an empty rootfs",
              file=sys.stderr)

    if False:
        rc = apply_config_lines(args.extra_config)
        if rc != 0:
            print("make_defconfig: FAIL: the config slice did not apply",
                  file=sys.stderr)
            return rc

    print("make_defconfig: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
