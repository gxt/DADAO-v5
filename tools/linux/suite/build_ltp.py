def build_case(source: Path, build: Path, case: suite_cases.Case,
               jobs: int, relink: bool = False) -> dict:
    """Build one LTP program (+ helpers) and stage it for the image.

    ``relink`` drops the previous product first: LTP's per-directory Makefiles
    link ``-lltp`` from ``LDLIBS``, which GNU make does not track as a
    prerequisite, so a rebuilt ``libltp.a`` (a patch to the test library, a new
    libc) would otherwise leave every case binary stale -- the suite would then
    rerun the *old* library and a fixed harness would still show the old
    verdict.
    """
    srcdir = f"testcases/{case.dir}"
    if not (source / srcdir / "Makefile").is_file():
        raise SetupError(f"{source / srcdir} is not an LTP test directory")
    staged = suite_paths.build_dir() / case.dir
    if relink:
        for name in (case.prog, *case.helpers):
            for stale in (build / srcdir / name, staged / name):
                if stale.is_file():
                    stale.unlink()
    log = suite_paths.ltp_root() / "logs" / f"build-{case.id}.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("wb") as stream:
        rc = 0
        for target in (case.prog, *case.helpers):
            stream.write(f"== make {srcdir} {target}\n".encode())
            stream.flush()
            cmd = ["make", "-C", str(build / srcdir),
                   "-f", str(source / srcdir / "Makefile"),
                   f"top_srcdir={source}", f"top_builddir={build}",
                   f"FILTER_OUT_LIBSRCS={FILTER_OUT_LIBSRCS}",
                   f"-j{jobs}", target]
            (build / srcdir).mkdir(parents=True, exist_ok=True)
            rc = subprocess.call(cmd, stdout=stream, stderr=subprocess.STDOUT,
                                 env=_make_env())
            if rc != 0:
                break

    staged.mkdir(parents=True, exist_ok=True)
    binary = build / srcdir / case.prog
    record = {"id": case.id, "rc": rc, "log": str(log),
              "binary": str(staged / case.prog), "sha256": None, "size": None,
              "helpers": []}
    if rc == 0 and binary.is_file():
        for name in (case.prog, *case.helpers):
            produced = build / srcdir / name
            if not produced.is_file():
                rc = 1
                break
            shutil.copy2(produced, staged / name)
            if name != case.prog:
                record["helpers"].append(
                    {"name": name, "sha256": _sha256_file(staged / name)})
        record["rc"] = rc
    if record["rc"] == 0:
        record["sha256"] = _sha256_file(staged / case.prog)
        record["size"] = (staged / case.prog).stat().st_size
        print(f"[PASS] build {case.id}: {record['size']} B "
              f"sha256={record['sha256'][:12]}")
    else:
        tail = log.read_text(encoding="utf-8", errors="replace").splitlines()[-12:]
        record["error"] = "\n".join(tail)
        print(f"[FAIL] build {case.id}: rc={record['rc']} (log {log.name})")
    return record


def build_cases(cases: list[suite_cases.Case], jobs: int | None = None) -> dict:
    """Build the given LTP cases; write the suite-wide ``build-report.json``."""
    jobs = jobs or int(os.environ.get("JOBS", "32"))
    ltp_cases = [case for case in cases if case.kind == "ltp"]
    if len(ltp_cases) != len(cases):
        raise SetupError("build_ltp only handles kind: ltp cases")
    source = ltp_source()
    state = source_state(source)
    prepared = prepare_build_tree(source)
    problems = check_config(prepared["build"])
    if problems:
        raise SetupError("config.h claims features this target lacks: "
                         + "; ".join(problems))
    lib = build_library(source, prepared, state, jobs)
    if lib["rc"] != 0:
        raise SetupError(f"libltp.a did not build (rc={lib['rc']}, log {lib['log']})")

    records = [build_case(source, prepared["build"], case, jobs,
                          relink=not lib["skipped"])
               for case in ltp_cases]
    report = {
        "format": 1,
        "suite": "ltp",
        "upstream": {"component": COMPONENT, "commit": state["base"],
                     "head": state["head"], "patches": state["patches"]},
        "toolchain": {"cc": str(prepared["wrapper"]), "target": TARGET,
                      "arch": "ltp",
                      "link": "static musl (public headers, libc.a + crt1.o)"},
        "headers": str(suite_paths.headers_dir() / "include"),
        "patches": series_entries(),
        "cases": records,
    }
    path = suite_paths.suite_root() / "build-report.json"
    path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                    encoding="utf-8")
    failed = [record["id"] for record in records if record["rc"] != 0]
    print(f"[INFO] build report: {path.name} "
          f"({len(records) - len(failed)}/{len(records)} built)")
    return {"report": report, "failed": failed}


def main() -> int:
    parser = argparse.ArgumentParser(description="cross-build the LTP subset")
    parser.add_argument("--only", action="append", default=[],
                        help="build only these case ids (repeatable; evidence)")
    parser.add_argument("--check-config", action="store_true",
                        help="only run the config.h compile probes")
    args = parser.parse_args()
    try:
        if args.check_config:
            source = ltp_source()
            prepared = prepare_build_tree(source)
            problems = check_config(prepared["build"])
            for problem in problems:
                print(f"[FAIL] {problem}")
            print(f"build_ltp: {'FAIL' if problems else 'PASS'} "
                  f"({len(PROBES) - len(problems)}/{len(PROBES)} probe(s))")
            return 1 if problems else 0
        cases = [case for case in suite_cases.load_cases(suite_cases.suite_yaml("ltp"))]
        if args.only:
            wanted = set(args.only)
            unknown = wanted - {case.id for case in cases}
            if unknown:
                raise SetupError(f"unknown case id(s) {sorted(unknown)}")
            cases = [case for case in cases if case.id in wanted]
        result = build_cases(cases)
    except (SetupError, suite_cases.SuiteError) as exc:
        print(f"build_ltp: SETUP ERROR: {exc}", file=sys.stderr)
        return 2
    if result["failed"]:
        print(f"build_ltp: FAIL: {len(result['failed'])} case(s) did not build: "
              f"{result['failed']}", file=sys.stderr)
        return 1
    print("build_ltp: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
