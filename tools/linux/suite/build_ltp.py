#!/usr/bin/env python3
"""build_ltp.py — cross-build the LTP subset (m18-linux-006).

LTP is a *locked component* (``manifests/components.lock.toml``): the source
tree under ``.work/source/ltp`` is read-only input, and every DADAO adaptation
is a reviewable patch of ``components/ltp/patches`` applied by
``tools/infra/apply_series.py``.  This module never edits the source tree; it
builds the subset out of tree, the way upstream's own build system supports:

    <suite root>/ltp/build            # top_builddir (this module writes it)
      include/mk/config.mk            # generated: CC wrapper, flags, prefixes
      include/mk/features.mk          # no optional tool/feature suite
      include/config.h                # copied from the in-repo data file
      include/lapi/syscalls.h         # upstream generator, run here
      lib/libltp.a                    # the test library
      testcases/.../<prog>            # the programs

Why not ``./configure``: LTP's Autotools ``configure`` is not shipped generated
(only ``configure.ac``) and the machine has no autoconf/automake; it also probes
features by *running* programs, which a cross target cannot do.  So the two
files configure would write are produced here instead, and every feature macro
they carry is asserted by a compile probe (``--check-config``) before it is
trusted -- a macro the target's headers no longer satisfy fails the build
instead of silently selecting a fallback shim.

Link model: static musl, exactly like the kselftest pilot, but with *public*
musl headers only (``include``, ``arch/<arch>``, ``obj/include``).  The internal
include dirs the kselftest wrapper adds (``src/internal``) define ``weak`` as a
macro and break ordinary identifiers; LTP programs are ordinary consumers, so
they get the public set.

Usage:
  python3 tools/linux/suite/build_ltp.py [--only ID ...] [--check-config]

Exit status: 0 = every requested case built; 1 = at least one case failed to
build (each failure is also in the report); 2 = setup error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.linux import paths as linux_paths        # noqa: E402
from tools.linux.suite import suite_cases           # noqa: E402
from tools.linux.suite import suite_paths           # noqa: E402

COMPONENT = "ltp"
TARGET = "dadao-unknown-elf"
#: In-repo data: the ``config.h`` Autotools would have written for this target.
CONFIG_H = suite_cases.SUITE_DIR / "ltp" / "config.h"
#: Legacy LIO wrapper: needs LTP's old ``test.h`` line discipline only, and no
#: subset case uses it (the modern ``tst_test`` layer calls the syscalls
#: directly).  Filtered explicitly, never silently: the filter is part of the
#: library stamp, so dropping it forces a rebuild.
FILTER_OUT_LIBSRCS = "tlibio.c"

#: Compile probes behind the ``HAVE_*`` macros this build depends on.  A macro
#: that claims a capability the target headers do not have is a setup error.
PROBES = {
    "HAVE_ATOMIC_MEMORY_MODEL":
        "#include <stdint.h>\nint32_t f(int32_t *v){return __atomic_add_fetch(v,1,5);}\n",
    "HAVE_STRUCT_FILE_HANDLE":
        "#include <fcntl.h>\nstruct file_handle *p; int main(void){return p != 0;}\n",
    "HAVE_SYS_TIMERFD_H":
        "#include <sys/timerfd.h>\nint main(void){return TFD_CLOEXEC;}\n",
    "HAVE_TIMERFD_CREATE":
        "#include <sys/timerfd.h>\nint main(void){return timerfd_create(0,0);}\n",
    "HAVE_TIMERFD_SETTIME":
        "#include <sys/timerfd.h>\nint main(void){return (long)timerfd_settime;}\n",
    "HAVE_TIMERFD_GETTIME":
        "#include <sys/timerfd.h>\nint main(void){return (long)timerfd_gettime;}\n",
    "HAVE_FALLOCATE":
        "#define _GNU_SOURCE\n#include <fcntl.h>\nint main(void){return fallocate(0,0,0,0);}\n",
    "HAVE_SETNS":
        "#define _GNU_SOURCE\n#include <sched.h>\nint main(void){return setns(0,0);}\n",
    "HAVE_STRUCT_LOOP_CONFIG":
        "#include <linux/loop.h>\nstruct loop_config *p; int main(void){return p != 0;}\n",
    "HAVE_PREADV":
        "#include <sys/uio.h>\nint main(void){return preadv(0,0,0,0);}\n",
    "HAVE_PWRITEV":
        "#include <sys/uio.h>\nint main(void){return pwritev(0,0,0,0);}\n",
    "HAVE_PREADV2":
        "#define _GNU_SOURCE\n#include <sys/uio.h>\nint main(void){return preadv2(0,0,0,0,0);}\n",
    "HAVE_PWRITEV2":
        "#define _GNU_SOURCE\n#include <sys/uio.h>\nint main(void){return pwritev2(0,0,0,0,0);}\n",
}

FEATURES_MK = """\
# Generated by tools/linux/suite/build_ltp.py (runtime artefact).
# No optional tool or sub-suite is used by the DADAO subset.
WITH_EXPECT := 0
WITH_PERL := 0
WITH_PYTHON := 0
METADATA_GENERATOR := 0
WITH_METADATA := 0
WITH_METADATA_HTML := 0
WITH_METADATA_PDF := 0
WITH_OPEN_POSIX_TESTSUITE := 0
WITH_KVM_TESTSUITE := 0
"""


class SetupError(RuntimeError):
    """Missing prerequisite / unusable input (exit 2)."""


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


# ---------------------------------------------------------------------------
# source tree
# ---------------------------------------------------------------------------

def ltp_source() -> Path:
    source = linux_paths.component_source_dir(COMPONENT)
    if not (source / "lib" / "tst_test.c").is_file():
        raise SetupError(f"{source} is not the LTP tree — run 'make fetch' first")
    return source


def _git(source: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(source), *args],
                          capture_output=True, text=True)


def locked_component() -> dict:
    import tomllib
    lock = _REPO_ROOT / "manifests" / "components.lock.toml"
    with lock.open("rb") as stream:
        data = tomllib.load(stream)
    for component in data.get("component", []):
        if component.get("name") == COMPONENT:
            return component
    raise SetupError(f"{lock.name} has no {COMPONENT} component")


def series_entries() -> list[str]:
    """Non-comment lines of ``components/ltp/series`` (the expected commit count)."""
    lock = locked_component()
    series = _REPO_ROOT / lock["patch_series"]
    if not series.is_file():
        raise SetupError(f"{series} is missing (docs/Process-01 §2)")
    return [line.strip() for line in series.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.strip().startswith("#")]


def source_state(source: Path) -> dict:
    """``(head, base, ahead, dirty)`` + the E1 judgement for the locked tree.

    The build consumes exactly ``base + patch series``; anything else (a dirty
    tree, a manually checked-out commit, a different patch count) would make the
    recorded binaries unattributable, so it is a setup error.
    """
    lock = locked_component()
    base = lock["commit"]
    head = _git(source, "rev-parse", "HEAD").stdout.strip()
    count = _git(source, "rev-list", "--count", f"{base}..HEAD").stdout.strip()
    dirty = _git(source, "status", "--porcelain=v1").stdout.strip()
    expected = 1 if series_entries() else 0
    problems = []
    if dirty:
        raise SetupError(
            f"{source} is dirty (uncommitted changes); the suite must build the "
            f"locked+patched tree — see docs/Process-01 §6.1")
    if not count.isdigit():
        problems.append(f"cannot count {base[:12]}..HEAD")
    elif int(count) != expected:
        problems.append(
            f"HEAD is base+{int(count)} but the series has {len(series_entries())} "
            f"patch(es) (expected base+{expected}); run `make fetch` + "
            f"`apply_series.py --component {COMPONENT}`")
    if problems:
        raise SetupError("; ".join(problems))
    return {"base": base, "head": head, "patches": expected}


