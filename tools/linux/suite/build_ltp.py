def _tool(name: str) -> Path:
    path = linux_paths.toolchain_bin() / name
    if not path.is_file():
        raise SetupError(f"{path} not found — run 'make install-host' first")
    return path


def write_cc_wrapper() -> Path:
    """Static-musl cross CC for LTP programs (public musl headers only)."""
    clang = _tool("clang")
    musl = linux_paths.component_source_dir("musl")
    for rel in ("lib/crt1.o", "lib/libc.a"):
        if not (musl / rel).is_file():
            raise SetupError(f"{musl / rel} not found — run 'make build-musl' first")
    builtins = subprocess.run(
        [str(clang), f"--target={TARGET}", "-rtlib=compiler-rt",
         "-print-libgcc-file-name"],
        capture_output=True, text=True)
    if builtins.returncode != 0 or not Path(builtins.stdout.strip()).is_file():
        raise SetupError("cannot resolve the target builtins archive — "
                         "run 'make install-host'")
    includes = " ".join(f'-I"{musl / d}"' for d in (
        "arch/dadao", "arch/generic", "obj/include", "include"))
    body = (
        "#!/bin/sh\n"
        "# Generated by tools/linux/suite/build_ltp.py (runtime artefact).\n"
        f'CLANG="{clang}"\n'
        f'MUSL="{musl}"\n'
        f'BUILTINS="{builtins.stdout.strip()}"\n'
        f'INC="{includes}"\n'
        'for a in "$@"; do\n'
        '  case "$a" in\n'
        '    -c|-E|-S) exec "$CLANG" --target=' + TARGET + ' -fintegrated-as '
        '$INC "$@";;\n'
        '  esac\n'
        'done\n'
        'exec "$CLANG" --target=' + TARGET + ' -fintegrated-as $INC '
        '-static -nostdlib "$MUSL/lib/crt1.o" "$@" '
        '-Wl,--start-group -L"$MUSL/lib" -lc "$BUILTINS" -Wl,--end-group\n'
    )
    path = suite_paths.ltp_cc_wrapper()
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != body:
        path.write_text(body, encoding="utf-8")
    path.chmod(0o755)
    return path


def config_mk(wrapper: Path, source: Path) -> str:
    """The file Autotools would write as ``include/mk/config.mk``."""
    toolchain = linux_paths.toolchain_bin()
    build = suite_paths.ltp_build_dir()
    prefix = build / "install"
    return f"""\
# Generated by tools/linux/suite/build_ltp.py (runtime artefact).
# Values are this target's, not a host configure result: static musl, no
# optional libraries, prefix inside the disposable build tree.
AR := {toolchain / 'llvm-ar'}
CC := {wrapper}
RANLIB := {toolchain / 'llvm-ranlib'}
STRIP := {toolchain / 'llvm-strip'}
OBJCOPY := {toolchain / 'llvm-objcopy'}
HOSTCC := cc
build := x86_64-pc-linux-gnu
host := {TARGET}
prefix := {prefix}
datarootdir := $(prefix)/share
includedir := $(prefix)/include
exec_prefix := $(prefix)
bindir := $(prefix)/bin
libdir := $(prefix)/lib
mandir := $(prefix)/man
CPPFLAGS := -I{build}/include -isystem {suite_paths.headers_dir()}/include
CFLAGS := -O2 -fno-strict-aliasing -Wall -std=gnu99
LDLIBS :=
LDFLAGS :=
LINUX_VERSION := {_kernel_release(source)}
LINUX_DIR :=
LINUX_VERSION_MAJOR := 7
LINUX_VERSION_PATCH := 2
WITH_MODULES := 0
HOST_CPU := dadao
"""


def _kernel_release(source: Path) -> str:
    """Kernel version the uapi headers come from (kernel tree next to LTP)."""
    makefile = linux_paths.linux_source_dir() / "Makefile"
    version = {"VERSION": "0", "PATCHLEVEL": "0", "SUBLEVEL": "0"}
    try:
        text = makefile.read_text(encoding="utf-8")
    except OSError:
        return "0.0.0"
    for line in text.splitlines():
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if key in version and value.isdigit():
            version[key] = value
    return f"{version['VERSION']}.{version['PATCHLEVEL']}.{version['SUBLEVEL']}"


def prepare_build_tree(source: Path) -> dict:
    """Write the configure files, the uapi header list and the wrapper."""
    build = suite_paths.ltp_build_dir()
    (build / "include" / "mk").mkdir(parents=True, exist_ok=True)
    (build / "include" / "lapi").mkdir(parents=True, exist_ok=True)

    # The subset compiles against the kernel uapi headers.  The kselftest pilot
    # installs them into the same suite root; an LTP-only work root (e.g. a
    # private replay of the locked kernel tree) has none yet, so install them
    # here rather than depending on another suite having run first.
    if not (suite_paths.headers_dir() / "include" / "linux" / "futex.h").is_file():
        from tools.linux.suite import build_suite
        build_suite.install_headers()

    if not CONFIG_H.is_file():
        raise SetupError(f"{CONFIG_H} is missing (in-repo target config)")
    shutil.copy2(CONFIG_H, build / "include" / "config.h")

    wrapper = write_cc_wrapper()
    (build / "include" / "mk" / "config.mk").write_text(
        config_mk(wrapper, source), encoding="utf-8")
    (build / "include" / "mk" / "features.mk").write_text(FEATURES_MK,
                                                          encoding="utf-8")

    syscalls = build / "include" / "lapi" / "syscalls.h"
    generator = source / "include" / "lapi" / "syscalls" / "generate_syscalls.sh"
    proc = subprocess.run(["sh", str(generator), str(syscalls)],
                          capture_output=True, text=True)
    if proc.returncode != 0 or not syscalls.is_file():
        raise SetupError(f"lapi/syscalls.h generation failed (rc={proc.returncode}): "
                         f"{proc.stderr.strip()}")
    return {"wrapper": wrapper, "build": build, "config_h": _sha256_file(CONFIG_H)}


def check_config(build: Path) -> list[str]:
    """Compile every probe behind a ``HAVE_*`` macro the config declares."""
    wrapper = suite_paths.ltp_cc_wrapper()
    scratch = build / "probe"
    scratch.mkdir(parents=True, exist_ok=True)
    declared = {line.split()[1] for line in
                (build / "include" / "config.h").read_text(encoding="utf-8").splitlines()
                if line.startswith("#define HAVE_")}
    problems = []
    # The probe table is the contract: a feature macro the build depends on must
    # be declared *and* compile.  A macro that silently disappears from config.h
    # is therefore red too (otherwise removing a line would shrink the check set
    # instead of failing).
    for macro in sorted(set(PROBES) - declared):
        problems.append(f"{macro}: declared feature macro is missing from config.h")
    for macro in sorted(declared - set(PROBES)):
        problems.append(f"{macro}: no probe (a feature macro without evidence)")
    for macro in sorted(declared & set(PROBES)):
        snippet = PROBES[macro]
        source = scratch / f"{macro}.c"
        source.write_text(snippet, encoding="utf-8")
        proc = subprocess.run(
            [str(wrapper), "-c", "-o", str(scratch / f"{macro}.o"),
             "-I", str(build / "include"),
             "-isystem", str(suite_paths.headers_dir() / "include"),
             str(source)],
            capture_output=True, text=True)
        if proc.returncode != 0:
            problems.append(f"{macro}: probe does not compile: "
                            f"{proc.stderr.strip().splitlines()[:2]}")
    return problems


