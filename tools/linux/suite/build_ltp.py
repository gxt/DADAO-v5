def library_stamp(state: dict, prepared: dict) -> dict:
    return {
        "base": state["base"],
        "head": state["head"],
        "config_h": prepared["config_h"],
        "config_mk": _sha256_file(prepared["build"] / "include" / "mk" / "config.mk"),
        "features_mk": _sha256_file(prepared["build"] / "include" / "mk" / "features.mk"),
        "wrapper": _sha256_file(prepared["wrapper"]),
        "filter_out": FILTER_OUT_LIBSRCS,
    }


def build_library(source: Path, prepared: dict, state: dict, jobs: int) -> dict:
    """Build ``lib/libltp.a`` (idempotent: skipped when the stamp matches)."""
    build = prepared["build"]
    stamp_path = suite_paths.ltp_root() / "lib-stamp.json"
    stamp = library_stamp(state, prepared)
    library = build / "lib" / "libltp.a"
    if stamp_path.is_file() and library.is_file():
        saved = json.loads(stamp_path.read_text(encoding="utf-8"))
        if saved == stamp:
            print(f"[INFO] libltp.a: unchanged (stamp {stamp['head'][:12]}) — skipped")
            return {"rc": 0, "log": None, "skipped": True}
    (build / "lib").mkdir(parents=True, exist_ok=True)
    log = suite_paths.ltp_root() / "logs" / "build-lib.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["make", "-C", str(build / "lib"),
           "-f", str(source / "lib" / "Makefile"),
           f"top_srcdir={source}", f"top_builddir={build}",
           f"FILTER_OUT_LIBSRCS={FILTER_OUT_LIBSRCS}", f"-j{jobs}"]
    with log.open("wb") as stream:
        rc = subprocess.call(cmd, stdout=stream, stderr=subprocess.STDOUT,
                             env=_make_env())
    if rc == 0 and library.is_file():
        stamp_path.write_text(json.dumps(stamp, indent=2, sort_keys=True) + "\n",
                              encoding="utf-8")
        print(f"[PASS] build libltp.a: {library.stat().st_size} B "
              f"sha256={_sha256_file(library)[:12]}")
    else:
        print(f"[FAIL] build libltp.a: rc={rc} (log {log})")
    return {"rc": rc, "log": str(log), "skipped": False}


def _make_env() -> dict:
    env = dict(os.environ)
    env.pop("MAKEFLAGS", None)
    return env


