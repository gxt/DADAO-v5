/*
 * TESTCASES-058t -- dot products and a 4x4 GEMM with fused multiply-add.
 *
 * Two C spellings of the same accumulator update are run over the same data:
 *   form=fma       `acc = fma(a[i], b[i], acc)`      (explicit, one fofma per
 *                                                      iteration)
 *   form=contract  `acc += a[i] * b[i]`              (frontend contracts to
 *                                                      llvm.fmuladd, also one
 *                                                      fofma, zero copy)
 * and a 4x4 GEMM `c[i][j] = sum_k fma(a[i][k], b[k][j], 0)`.
 *
 * The data are generated by the LCG documented in oracle_fma.py (the value is
 * (int32)u / 2^31, exactly representable).  The probe prints the data hash and
 * a hash of EVERY intermediate accumulator, so the oracle compares the whole
 * sequence bit for bit, not just the final sum.  Expectations (and the
 * accumulated rf0 flags) come from oracle_fma.py, never from QEMU.
 *
 * The three kernels are `noinline` so the driver can assert the instruction
 * mix of each one separately at both -O0 and -O2 (dot_run/gemm4 would
 * otherwise be inlined into main at -O2).
 */
#include "fma_common.h"

#define DOT_MAX 256

static unsigned long long dot_data_hash(const double *a, const double *b,
					int n)
{
	unsigned long long h = FMA_FNV_INIT;
	int i;

	for (i = 0; i < n; i++)
		h = fma_fnv_u64(h, fma_bits_d(a[i]));
	for (i = 0; i < n; i++)
		h = fma_fnv_u64(h, fma_bits_d(b[i]));
	return h;
}

__attribute__((noinline))
static unsigned long long dot_fma_run(const double *a, const double *b, int n,
				      unsigned long long *h,
				      unsigned long long *pre,
				      unsigned long long *post)
{
	double acc = 0.0;
	unsigned long long hash = FMA_FNV_INIT;
	int i;

	fma_clear_flags();
	*pre = fma_rd_rf0();
	for (i = 0; i < n; i++) {
		acc = fma(a[i], b[i], acc);		/* 1 fofma, no copy */
		hash = fma_fnv_u64(hash, fma_bits_d(acc));
	}
	*post = fma_rd_rf0_dep(hash);
	*h = hash;
	return fma_bits_d(acc);
}

__attribute__((noinline))
static unsigned long long dot_contract_run(const double *a, const double *b,
					   int n, unsigned long long *h,
					   unsigned long long *pre,
					   unsigned long long *post)
{
	double acc = 0.0;
	unsigned long long hash = FMA_FNV_INIT;
	int i;

	fma_clear_flags();
	*pre = fma_rd_rf0();
	for (i = 0; i < n; i++) {
		acc += a[i] * b[i];			/* llvm.fmuladd */
		hash = fma_fnv_u64(hash, fma_bits_d(acc));
	}
	*post = fma_rd_rf0_dep(hash);
	*h = hash;
	return fma_bits_d(acc);
}

/* 4x4 GEMM; the k-loop body is exactly one fofma per k. */
__attribute__((noinline))
static void gemm4(const double *a, const double *b, double *c)
{
	int i, j, k;

	for (i = 0; i < 4; i++) {
		for (j = 0; j < 4; j++) {
			double acc = 0.0;

			for (k = 0; k < 4; k++)
				acc = fma(a[i * 4 + k], b[k * 4 + j], acc);
			c[i * 4 + j] = acc;
		}
	}
}

int main(void)
{
	static const int lens[] = { 16, 64, 256 };
	double a[DOT_MAX], b[DOT_MAX];
	double ga[16], gb[16], gc[16];
	unsigned long long init = fma_rd_rf0();
	unsigned long long data, hash, pre, post, out;
	int li, i;

	printf("INIT rf0=%016llx\n", init);

	for (li = 0; li < (int)(sizeof(lens) / sizeof(lens[0])); li++) {
		int n = lens[li];
		unsigned int sa = (unsigned int)(0x12345678u + (unsigned)n);
		unsigned int sb = (unsigned int)(0x0BADF00Du + (unsigned)n);

		fma_gen(sa, a, n);
		fma_gen(sb, b, n);
		data = dot_data_hash(a, b, n);
		out = dot_fma_run(a, b, n, &hash, &pre, &post);
		printf("ALG group=dot fmt=fo len=%d form=fma data=%016llx "
		       "hash=%016llx out=%016llx pre=%016llx post=%016llx "
		       "rm=0\n", n, data, hash, out, pre, post);
		out = dot_contract_run(a, b, n, &hash, &pre, &post);
		printf("ALG group=dot fmt=fo len=%d form=contract data=%016llx "
		       "hash=%016llx out=%016llx pre=%016llx post=%016llx "
		       "rm=0\n", n, data, hash, out, pre, post);
	}

	fma_gen(0x11111111u, ga, 16);
	fma_gen(0x22222222u, gb, 16);
	data = FMA_FNV_INIT;
	for (i = 0; i < 16; i++)
		data = fma_fnv_u64(data, fma_bits_d(ga[i]));
	for (i = 0; i < 16; i++)
		data = fma_fnv_u64(data, fma_bits_d(gb[i]));
	fma_clear_flags();
	pre = fma_rd_rf0();
	gemm4(ga, gb, gc);
	post = fma_rd_rf0_dep(fma_bits_d(gc[15]));
	for (i = 0; i < 16; i++) {
		if (i == 0)
			printf("ALG group=gemm fmt=fo row=0 col=0 data=%016llx "
			       "out=%016llx pre=%016llx post=%016llx rm=0\n",
			       data, fma_bits_d(gc[i]), pre, post);
		else
			printf("ALG group=gemm fmt=fo row=%d col=%d "
			       "data=%016llx out=%016llx\n", i / 4, i % 4,
			       data, fma_bits_d(gc[i]));
	}

	fma_restore("dot", init);
	return 0;
}
